"""Compare layer commands in order, or write a compact normalized oracle fixture.

Normalization removes comments, progress and object labels, sorts numeric words,
and converts absolute extrusion to relative extrusion. It deliberately preserves
move boundaries, feedrate-only commands, acceleration, fan and temperature commands.
The layer range ends at the final TYPE:Custom (shutdown), including the preceding
retract/fan-off. XYZ/IJK/R tolerance is 0.002 mm, E 0.0001 mm, F 1 mm/min;
other command parameters must agree exactly. Exit 1 means differences, 2 bad input.
"""

import argparse
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
import re
import sys


@dataclass
class Command:
    code: str
    words: dict
    line: int

    def text(self):
        return " ".join([self.code] + [f"{k}{v:.9g}" for k, v in sorted(self.words.items())])


def read(path):
    lines = Path(path).read_text().splitlines()
    starts = [i for i, line in enumerate(lines) if line.strip() == ";LAYER_CHANGE"]
    if not starts:
        raise ValueError(f"{path}: no ;LAYER_CHANGE markers")
    end = next((i for i in range(starts[-1] + 1, len(lines))
                if lines[i].strip() == ";TYPE:Custom"), len(lines))
    layers = []
    relative = True  # Normalized fixtures are relative E; raw files supply M82/M83.
    extrusion = 0.0
    for i, raw in enumerate(lines[:end]):
        if raw.strip() == ";LAYER_CHANGE":
            layers.append([])
        line = raw.split(";", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        code = parts[0].upper()
        if not layers and code not in {"M82", "M83", "G92", "G0", "G1", "G2", "G3"}:
            continue
        if code in {"M73", "M486", "M117", "EXCLUDE_OBJECT_START",
                    "EXCLUDE_OBJECT_END", "EXCLUDE_OBJECT_DEFINE"}:
            continue
        words = {}
        for word in parts[1:]:
            match = re.fullmatch(r"([A-Za-z])([-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?)", word)
            if not match:
                raise ValueError(f"{path}:{i + 1}: unsupported word {word!r}")
            key, value = match.groups()
            if key.upper() in words:
                raise ValueError(f"{path}:{i + 1}: duplicate word {key}")
            words[key.upper()] = float(value)
        if code == "M82":
            relative = False
            code = "M83"  # The normalized stream always contains relative E.
        elif code == "M83":
            relative = True
        elif code == "G92" and "E" in words:
            extrusion = words["E"]
        elif code in {"G0", "G1", "G2", "G3"} and "E" in words:
            value = words["E"]
            words["E"] = value if relative else value - extrusion
            extrusion = extrusion + value if relative else value
        if layers:
            layers[-1].append(Command(code, words, i + 1))
    return layers


def differences(a, b):
    if a is None or b is None:
        return ["missing"]
    if a.code != b.code:
        return ["command"]
    result = []
    for key in sorted(a.words.keys() | b.words.keys()):
        tolerance = 0.002 if key in "XYZIJKR" else 0.0001 if key == "E" else 1.0 if key == "F" else 0.0
        if key not in a.words or key not in b.words:
            result.append(key + " presence")
        elif abs(a.words[key] - b.words[key]) > tolerance + 1e-10:
            result.append(key)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("actual", type=Path, nargs="?")
    parser.add_argument("--normalize", type=Path, metavar="OUTPUT")
    parser.add_argument("-n", "--first", type=int, default=3, help="first N differences per layer (default 3)")
    parser.add_argument("--layer", type=int, help="show details for this zero-based layer only")
    parser.add_argument("--only-layer", type=int, action="append", help="compare only this zero-based layer (repeatable)")
    args = parser.parse_args()
    reference = read(args.reference)
    if args.normalize:
        args.normalize.write_text("; Normalized relative-E layer commands; generated by scripts/gcode-exact-diff.py\n" +
                                  "".join(";LAYER_CHANGE\n" + "".join(c.text() + "\n" for c in layer)
                                          for layer in reference))
    if args.actual is None:
        if not args.normalize:
            parser.error("provide ACTUAL or --normalize OUTPUT")
        return 0
    actual = read(args.actual)
    count = bad_layers = 0
    categories = Counter()
    compared = 0
    for layer in range(max(len(reference), len(actual))):
        if args.only_layer is not None and layer not in args.only_layer:
            continue
        compared += 1
        a = reference[layer] if layer < len(reference) else []
        b = actual[layer] if layer < len(actual) else []
        changed = 0
        for j in range(max(len(a), len(b))):
            ca = a[j] if j < len(a) else None
            cb = b[j] if j < len(b) else None
            diff = differences(ca, cb)
            if not diff:
                continue
            changed += 1
            categories.update(diff)
            if changed <= args.first and (args.layer is None or args.layer == layer):
                print(f"layer {layer} command {j + 1}: {', '.join(diff)}")
                print(f"  ref {ca.line if ca else '-'}: {ca.text() if ca else '<missing>'}")
                print(f"  got {cb.line if cb else '-'}: {cb.text() if cb else '<missing>'}")
        if changed:
            bad_layers += 1
            count += changed
            if args.first and (args.layer is None or args.layer == layer):
                print(f"layer {layer}: {changed} differing commands; ref={len(a)}, got={len(b)}")
    if args.only_layer is not None and compared != len(set(args.only_layer)):
        raise ValueError("requested layer does not exist")
    print(f"SUMMARY: {count} differing commands in {bad_layers}/{compared} layers; "
          f"reference={sum(map(len, reference))}, actual={sum(map(len, actual))}")
    print("categories: " + ", ".join(f"{key}={value}" for key, value in sorted(categories.items())))
    return int(bool(count))


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        sys.exit(2)
