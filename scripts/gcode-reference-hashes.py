"""Slice/validate the gate fixtures (cube20 and 3DBenchy on every corpus printer) with SOURCE_DATE_EPOCH=0; print raw SHA-256.

--baseline accepts outputs named before-MODEL-PRINTER.gcode. It verifies that only
identity and the appended settings changed, and saves a complete unified diff.
All Mica processes use a new settings directory; output defaults to system temp.
"""
import argparse
import difflib
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
GENERIC = r'; generated by (.+?) on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}'
ALIAS = r'OrcaSlicer\s(.*)\son'


def program(text):
    for marker in ['; prusaslicer_config = begin', '; CONFIG_BLOCK_START']:
        text = text.split(marker)[0]
    return '\n'.join(l for l in text.rstrip().splitlines()
                     if not l.startswith('; generated by '))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary', type=Path, default=ROOT/'target/release/mica')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--baseline', type=Path)
    args = parser.parse_args()
    output = args.output or Path(tempfile.mkdtemp(prefix='mica-reference-hashes-'))
    output.mkdir(parents=True, exist_ok=True)
    profiles = json.loads((ROOT/'tests/corpus/manifest.json').read_text())['printers']
    results = []
    with tempfile.TemporaryDirectory(prefix='mica-hash-settings-') as settings:
        env = dict(os.environ, SOURCE_DATE_EPOCH='0', MICA_CONFIG_DIR=settings)
        for model in ['cube20', '3DBenchy']:
            for printer, profile in profiles.items():
                path = output/f'after-{model}-{printer}.gcode'
                run = subprocess.run([str(args.binary.resolve()), 'slice',
                    str(ROOT/f'tests/models/{model}.stl'), *profile, '-o', str(path)],
                    env=env, capture_output=True, text=True)
                if run.returncode:
                    raise RuntimeError(run.stderr)
                check = subprocess.run([str(args.binary.resolve()),'validate',str(path),
                    *profile,'--json'], env=env, capture_output=True, text=True)
                data = json.loads(check.stdout)
                assert check.returncode == 0 and data['errors'] == 0, data
                text = path.read_text()
                identity = next(l for l in text.splitlines() if l.startswith('; generated by '))
                match = re.search(GENERIC, identity)
                assert match and match[1].startswith('Mica Slicer '), identity
                alias = re.search(ALIAS, identity)
                assert bool(alias) == (printer == 'u1'), identity
                if alias:
                    assert alias[1] == '2.4.2', alias[1]
                result = dict(model=model, printer=printer, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                              errors=data['errors'], identity=identity, generic_name=match[1],
                              alias_version=alias[1] if alias else None)
                if args.baseline:
                    old_path = args.baseline/f'before-{model}-{printer}.gcode'
                    old = old_path.read_text()
                    assert program(old) == program(text), f'executable or other comments changed: {path}'
                    diff = ''.join(difflib.unified_diff(old.splitlines(True),text.splitlines(True),
                                   fromfile=str(old_path),tofile=str(path)))
                    (output/f'{model}-{printer}.diff').write_text(diff)
                    result['before_sha256'] = hashlib.sha256(old_path.read_bytes()).hexdigest()
                    result['program_unchanged'] = True
                results.append(result)
                print(f'{result["sha256"]}  {path.name}', flush=True)
    (output/'hashes.json').write_text(json.dumps(results,indent=2)+'\n')
    print(f'All {len(results)} validated; regex checks passed. Artifacts: {output}')


if __name__ == '__main__':
    main()
