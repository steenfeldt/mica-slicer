//! `cargo xtask gen-prusa-options <defaults.ini>`: regenerates Mica's table of PrusaSlicer options.
//!
//! Inputs, all from the pinned `prusaslicer` checkout plus PrusaSlicer itself:
//! - option names, types and nullability from `src/libslic3r/PrintConfig.cpp` (`this->add(...)`)
//! - which preset (print / filament / printer) owns each option, from `src/libslic3r/Preset.cpp`
//! - default values from a config saved by the pinned PrusaSlicer release with an empty data dir:
//!   `PrusaSlicer --datadir <empty dir> --save defaults.ini`
//!
//! Output: `crates/mica-core/src/config/prusa_options.tsv` (key, type, nullable, scope, default).

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;
use std::process::ExitCode;

const OUTPUT: &str = "crates/mica-core/src/config/prusa_options.tsv";

pub fn run(root: &Path, defaults_ini: Option<&str>) -> ExitCode {
    let Some(defaults_ini) = defaults_ini else {
        eprintln!(
            "usage: cargo xtask gen-prusa-options <defaults.ini saved by the pinned PrusaSlicer>"
        );
        return ExitCode::from(2);
    };
    let ps = root.join("upstream/prusaslicer");
    let read = |p: &Path| fs::read_to_string(p).map_err(|e| format!("{}: {e}", p.display()));
    let (config_cpp, preset_cpp, defaults) = match (
        read(&ps.join("src/libslic3r/PrintConfig.cpp")),
        read(&ps.join("src/libslic3r/Preset.cpp")),
        read(Path::new(defaults_ini)),
    ) {
        (Ok(a), Ok(b), Ok(c)) => (a, b, c),
        (a, b, c) => {
            for e in [a.err(), b.err(), c.err()].into_iter().flatten() {
                eprintln!("{e}");
            }
            eprintln!("(fetch upstream sources with scripts/fetch-upstream.sh)");
            return ExitCode::FAILURE;
        }
    };

    let mut types = option_types(&config_cpp);
    let mut scopes = option_scopes(&preset_cpp);
    // Options PrusaSlicer defines in loops, which the scan above cannot see.
    let candidates: Vec<String> = defaults_keys(&defaults)
        .into_iter()
        .map(str::to_string)
        .chain(scopes.keys().cloned())
        .collect();
    for key in candidates.iter().map(String::as_str) {
        if key.starts_with("machine_max_") {
            types.entry(key.to_string()).or_insert(("Floats", false));
        } else if key == "filament_seam_gap_distance" {
            types
                .entry(key.to_string())
                .or_insert(("FloatsOrPercents", true));
        } else if let Some(base) = key.strip_prefix("filament_")
            && let Some(&(ty, _)) = types.get(base)
        {
            // Filament overrides of printer retraction settings: same type, nullable.
            types.entry(key.to_string()).or_insert((ty, true));
        }
    }
    // Per-extruder options live in the printer preset.
    for key in list_body(&config_cpp, "m_extruder_option_keys = {") {
        scopes.entry(key).or_insert("printer");
    }
    let defaults: BTreeMap<&str, &str> = defaults
        .lines()
        .filter(|l| !l.starts_with('#'))
        .filter_map(|l| {
            l.split_once(" = ")
                .or_else(|| l.strip_suffix(" =").map(|k| (k, "")))
        })
        .collect();

    let commit = std::process::Command::new("git")
        .args(["-C", &ps.to_string_lossy(), "rev-parse", "HEAD"])
        .output()
        .ok()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_default();

    let mut out = String::new();
    out.push_str("# PrusaSlicer FFF options: key, type, nullable, scope, default (PrusaSlicer serialization), ratio_over.\n");
    out.push_str(&format!(
        "# Generated by `cargo xtask gen-prusa-options` from prusaslicer@{} src/libslic3r/PrintConfig.cpp\n",
        commit.get(..10).unwrap_or("unknown")
    ));
    out.push_str("# (types), src/libslic3r/Preset.cpp (scopes) and defaults saved by PrusaSlicer 2.9.6. Do not edit.\n");
    // Every option that is in the defaults export or belongs to a preset, with its default:
    // from the export when present, otherwise nil for nullable options and empty for the rest.
    let mut keys: Vec<&str> = defaults.keys().copied().collect();
    keys.extend(scopes.keys().map(String::as_str));
    keys.extend(
        types
            .iter()
            .filter(|(k, (_, nullable))| *nullable && k.starts_with("filament_"))
            .map(|(k, _)| k.as_str()),
    );
    keys.sort_unstable();
    keys.dedup();
    let mut missing_type = Vec::new();
    let mut synthesized = Vec::new();
    for key in keys {
        let Some(&(ty, nullable)) = types.get(key) else {
            missing_type.push(key);
            continue;
        };
        let default = match defaults.get(key) {
            Some(d) if !nullable || *d == "nil" => d.to_string(),
            // Nullable overrides default to "not set", whatever the plain option's default is.
            _ if nullable => "nil".to_string(),
            _ => {
                synthesized.push(key);
                match ty {
                    "Bool" | "Int" | "Float" | "FloatOrPercent" => "0".to_string(),
                    "Percent" => "0%".to_string(),
                    "Point" => "0x0".to_string(),
                    "Enum" => enum_default(&config_cpp, key).unwrap_or_default(),
                    _ => String::new(), // strings and vectors: empty
                }
            }
        };
        let scope = scopes.get(key).copied().unwrap_or("-");
        let ratio = ratio_over(&config_cpp, key).unwrap_or_default();
        out.push_str(&format!(
            "{key}\t{ty}\t{}\t{scope}\t{default}\t{ratio}\n",
            u8::from(nullable)
        ));
    }
    if !synthesized.is_empty() {
        eprintln!("note: empty default used for {synthesized:?}");
    }
    if !missing_type.is_empty() {
        eprintln!("warning: no type found for {missing_type:?}");
    }
    let path = root.join(OUTPUT);
    if let Err(e) = fs::create_dir_all(path.parent().unwrap()).and_then(|()| fs::write(&path, out))
    {
        eprintln!("{}: {e}", path.display());
        return ExitCode::FAILURE;
    }
    println!("wrote {OUTPUT}");
    ExitCode::SUCCESS
}

/// `this->add("key", coType)` and `this->add_nullable("key", coType)`.
fn option_types(cpp: &str) -> BTreeMap<String, (&str, bool)> {
    let mut out = BTreeMap::new();
    for (marker, nullable) in [("this->add(\"", false), ("this->add_nullable(\"", true)] {
        let mut rest = cpp;
        while let Some(i) = rest.find(marker) {
            rest = &rest[i + marker.len()..];
            let Some(end) = rest.find('"') else { break };
            let key = &rest[..end];
            let after = rest[end + 1..].trim_start_matches([',', ' ']);
            let ty_end = after.find(')').unwrap_or(0);
            let ty = after[..ty_end].trim();
            if let Some(ty) = ty.strip_prefix("co") {
                // First definition wins (FFF params are defined before SLA/CLI ones).
                out.entry(key.to_string()).or_insert((leak(ty), nullable));
            }
        }
    }
    out
}

fn leak(s: &str) -> &'static str {
    Box::leak(s.to_string().into_boxed_str())
}

/// `def->ratio_over = "parent";` in the option's definition block: what a percentage is relative to.
fn ratio_over(cpp: &str, key: &str) -> Option<String> {
    let start = cpp.find(&format!("this->add(\"{key}\""))?;
    let block = &cpp[start..];
    let block = &block[..block[1..]
        .find("def = this->add")
        .map_or(block.len(), |i| i + 1)];
    let at = block.find("def->ratio_over = \"")? + "def->ratio_over = \"".len();
    Some(block[at..at + block[at..].find('"')?].to_string())
}

/// Default of an enum option, read from `set_default_value(new ConfigOptionEnum<T>(CONST))` and
/// translated through PrusaSlicer's `s_keys_map_T` table.
fn enum_default(cpp: &str, key: &str) -> Option<String> {
    let start = cpp.find(&format!("this->add(\"{key}\""))?;
    let block = &cpp[start..];
    let block = &block[..block[1..]
        .find("def = this->add")
        .map_or(block.len(), |i| i + 1)];
    let open = block.find("ConfigOptionEnum<")? + "ConfigOptionEnum<".len();
    let ty = &block[open..open + block[open..].find('>')?];
    let constant = block[open..].split(['(', ')']).nth(1)?.trim();
    let map_start = cpp.find(&format!("s_keys_map_{ty} {{"))?;
    let map = &cpp[map_start..];
    let map = &map[..map.find("};")?];
    map.lines().find_map(|line| {
        let (name, value) = line
            .trim()
            .trim_start_matches('{')
            .trim_end_matches(['}', ','])
            .split_once(',')?;
        (value.trim() == constant).then(|| name.trim().trim_matches('"').to_string())
    })
}

fn defaults_keys(ini: &str) -> Vec<&str> {
    ini.lines()
        .filter(|l| !l.starts_with('#'))
        .filter_map(|l| l.split_once(" =").map(|(k, _)| k))
        .collect()
}

/// Quoted strings in the `{ ... }` list that follows `marker`.
fn list_body(cpp: &str, marker: &str) -> Vec<String> {
    let Some(start) = cpp.find(marker) else {
        return Vec::new();
    };
    let body = &cpp[start + marker.len()..];
    let body = &body[..body.find("};").unwrap_or(body.len())];
    body.split('"')
        .skip(1)
        .step_by(2)
        .map(str::to_string)
        .collect()
}

/// Preset lists in Preset.cpp: which preset type owns which option.
fn option_scopes(cpp: &str) -> BTreeMap<String, &'static str> {
    let mut out = BTreeMap::new();
    for (list, scope) in [
        ("s_Preset_print_options", "print"),
        ("s_Preset_filament_options", "filament"),
        ("s_Preset_machine_limits_options", "printer"),
        ("s_Preset_printer_options", "printer"),
    ] {
        let Some(start) = cpp.find(&format!("static std::vector<std::string> {list} {{")) else {
            continue;
        };
        let body = &cpp[start..];
        let body = &body[..body.find("};").unwrap_or(body.len())];
        for part in body.split('"').skip(1).step_by(2) {
            out.insert(part.to_string(), scope);
        }
    }
    out
}
