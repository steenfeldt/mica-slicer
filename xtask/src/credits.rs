//! `cargo xtask gen-credits`: the open-source crate list of the About window's Open-source
//! licenses view and of the repository's `THIRD_PARTY_LICENSES.md`, generated from Cargo's own
//! dependency data instead of being written by hand.
//!
//! 1. `cargo tree` lists every crate the shipped binaries (`mica-gui`, `mica-cli`) link on any
//!    platform (normal dependencies only, default features: no development-only extras such
//!    as OpenH264), with its SPDX license expression and repository.
//! 2. Each crate's copyright lines are read from the license files in its unpacked source in
//!    Cargo's registry, so the list keeps the notices MIT- and BSD-style licenses ask for.
//! 3. The rows go to `crates/mica-gui/assets/credits/crates.tsv` (name, version, license,
//!    repository, copyright). Every license the list names must have its full text in
//!    `crates/mica-gui/assets/credits/licenses/<SPDX id>.txt`, or appear only as an
//!    alternative Mica does not take (`OPTIONAL_IDS`).
//! 4. The mica-gui test `credits::tests::third_party_licenses_are_current` rewrites
//!    `THIRD_PARTY_LICENSES.md` from the same data.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

pub const TSV: &str = "crates/mica-gui/assets/credits/crates.tsv";
pub const LICENSES: &str = "crates/mica-gui/assets/credits/licenses";

/// License ids that only ever appear as an `OR` alternative to a permissive license Mica takes
/// instead; no text is bundled for them.
const OPTIONAL_IDS: &[&str] = &[
    "GPL-2.0-only",
    "LGPL-2.1-or-later",
    "Apache-2.0 WITH LLVM-exception",
];

#[derive(Debug, PartialEq, Eq, PartialOrd, Ord)]
struct Row {
    name: String,
    version: String,
    license: String,
    repository: String,
    copyright: String,
}

pub fn run(root: &Path) -> ExitCode {
    let rows = match crates(root) {
        Ok(r) => r,
        Err(e) => {
            eprintln!("gen-credits: {e}");
            return ExitCode::FAILURE;
        }
    };
    let mut out = String::from(
        "# Generated by `cargo xtask gen-credits` from `cargo tree` (mica-gui + mica-cli, every\n\
         # platform, normal dependencies) and each crate's license files. Do not edit.\n\
         # name\tversion\tlicense\trepository\tcopyright\n",
    );
    for r in &rows {
        out += &format!(
            "{}\t{}\t{}\t{}\t{}\n",
            r.name, r.version, r.license, r.repository, r.copyright
        );
    }
    if let Err(e) = fs::write(root.join(TSV), out) {
        eprintln!("gen-credits: could not write {TSV}: {e}");
        return ExitCode::FAILURE;
    }
    println!("wrote {TSV} ({} crates)", rows.len());
    let mut missing = BTreeSet::new();
    for r in &rows {
        for id in license_ids(&r.license) {
            if !OPTIONAL_IDS.contains(&id.as_str())
                && !root.join(LICENSES).join(format!("{id}.txt")).is_file()
            {
                missing.insert(id);
            }
        }
    }
    if !missing.is_empty() {
        eprintln!(
            "gen-credits: add the full text of {} under {LICENSES}/",
            missing.into_iter().collect::<Vec<_>>().join(", ")
        );
        return ExitCode::FAILURE;
    }
    let status = Command::new(cargo())
        .args([
            "test",
            "--offline",
            "--profile",
            &crate::profile(),
            "-p",
            "mica-gui",
            "--",
            "--exact",
            "credits::tests::third_party_licenses_are_current",
        ])
        .env("MICA_WRITE_CREDITS", "1")
        .current_dir(root)
        .status();
    if status.is_ok_and(|s| s.success()) {
        println!("wrote THIRD_PARTY_LICENSES.md");
        ExitCode::SUCCESS
    } else {
        eprintln!("gen-credits: could not generate THIRD_PARTY_LICENSES.md");
        ExitCode::FAILURE
    }
}

fn cargo() -> String {
    std::env::var("CARGO").unwrap_or_else(|_| "cargo".into())
}

/// The SPDX ids in a license expression (`MIT OR Apache-2.0`, `MIT/Apache-2.0`, `Apache-2.0
/// WITH LLVM-exception`): one id per alternative, a `WITH` exception kept with its license.
pub fn license_ids(expr: &str) -> Vec<String> {
    let flat = expr.replace(['(', ')'], " ").replace('/', " OR ");
    let mut out: Vec<String> = vec![];
    let mut words = flat.split_whitespace().peekable();
    while let Some(w) = words.next() {
        if w == "OR" || w == "AND" {
            continue;
        }
        if words.peek() == Some(&"WITH") {
            words.next();
            let exception = words.next().unwrap_or_default();
            out.push(format!("{w} WITH {exception}"));
        } else {
            out.push(w.to_string());
        }
    }
    out.dedup();
    out
}

fn crates(root: &Path) -> Result<Vec<Row>, String> {
    let output = Command::new(cargo())
        .args([
            "tree",
            "--offline",
            "-p",
            "mica-gui",
            "-p",
            "mica-cli",
            "-e",
            "normal",
            "--target",
            "all",
            "--prefix",
            "none",
            "--format",
            "{p}\t{l}\t{r}",
        ])
        .current_dir(root)
        .output()
        .map_err(|e| format!("could not run cargo tree: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "cargo tree failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    let registry = registry_dirs();
    let mut rows: BTreeMap<(String, String), Row> = BTreeMap::new();
    for line in String::from_utf8_lossy(&output.stdout).lines() {
        let mut cols = line.split('\t');
        let (Some(pkg), Some(license), repository) = (cols.next(), cols.next(), cols.next()) else {
            continue;
        };
        // "name v1.2.3", "name v1.2.3 (*)" (seen before), "name v0.0.1 (/path)" (this workspace).
        let mut parts = pkg.split_whitespace();
        let (Some(name), Some(version)) = (parts.next(), parts.next()) else {
            continue;
        };
        if parts.any(|p| p.starts_with("(/") || p.starts_with("(file:")) {
            continue;
        }
        let version = version.trim_start_matches('v').to_string();
        let repository = repository
            .unwrap_or_default()
            .trim_end_matches(" (*)")
            .trim()
            .to_string();
        let key = (name.to_string(), version.clone());
        if rows.contains_key(&key) {
            continue;
        }
        let copyright = registry
            .iter()
            .map(|d| d.join(format!("{name}-{version}")))
            .find(|d| d.is_dir())
            .map(|d| copyright_lines(&d))
            .unwrap_or_default();
        rows.insert(
            key,
            Row {
                name: name.to_string(),
                version,
                license: license.trim().to_string(),
                repository,
                copyright,
            },
        );
    }
    if rows.is_empty() {
        return Err("cargo tree listed no crates".into());
    }
    Ok(rows.into_values().collect())
}

/// The unpacked crate sources of Cargo's registries (`$CARGO_HOME/registry/src/*`).
fn registry_dirs() -> Vec<PathBuf> {
    let home = std::env::var_os("CARGO_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".cargo")));
    let Some(src) = home.map(|h| h.join("registry").join("src")) else {
        return vec![];
    };
    let mut dirs: Vec<PathBuf> = fs::read_dir(src)
        .into_iter()
        .flatten()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.is_dir())
        .collect();
    dirs.sort();
    dirs
}

/// The distinct copyright lines of a crate's license and notice files, joined with " · ".
fn copyright_lines(dir: &Path) -> String {
    let mut files: Vec<PathBuf> = fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .map(|e| e.path())
        .filter(|p| {
            p.is_file()
                && p.file_name()
                    .and_then(|n| n.to_str())
                    .map(|n| n.to_ascii_uppercase())
                    .is_some_and(|n| {
                        [
                            "LICENSE",
                            "LICENCE",
                            "COPYING",
                            "COPYRIGHT",
                            "NOTICE",
                            "UNLICENSE",
                        ]
                        .iter()
                        .any(|s| n.starts_with(s))
                    })
        })
        .collect();
    files.sort();
    let mut lines: Vec<String> = vec![];
    for f in files {
        let Ok(text) = fs::read_to_string(&f) else {
            continue;
        };
        for line in text.lines() {
            let l = line.trim().trim_start_matches(['#', '*', '/']).trim();
            let lower = l.to_lowercase();
            let is_notice = lower.starts_with("copyright") || l.starts_with('©');
            // Template lines of the license texts themselves.
            let template = [
                "[yyyy]",
                "<year>",
                "{yyyy}",
                "[year]",
                "<copyright",
                "[name of",
                "owner]",
                "holders>",
                "notice",
                "license",
                "licence",
                "copyright and related",
                "copyright (c) <",
            ]
            .iter()
            .any(|t| lower.contains(t))
                || lower == "copyright"
                || l.len() < 12;
            if is_notice && !template {
                let mut l: String = l.split_whitespace().collect::<Vec<_>>().join(" ");
                if l.chars().count() > 160 {
                    l = l.chars().take(157).collect::<String>() + "…";
                }
                // "Copyright (c) 2023 X" and "Copyright 2023 X" are the same notice.
                let key = |s: &str| {
                    s.to_lowercase()
                        .replace("(c)", "")
                        .replace('©', "")
                        .split_whitespace()
                        .collect::<Vec<_>>()
                        .join(" ")
                        .trim_end_matches('.')
                        .to_string()
                };
                if !lines.iter().any(|x| key(x) == key(&l)) {
                    lines.push(l);
                }
            }
        }
    }
    lines.truncate(3);
    lines.join(" · ").replace('\t', " ")
}

#[cfg(test)]
mod tests {
    use super::license_ids;

    #[test]
    fn splits_license_expressions() {
        assert_eq!(license_ids("MIT OR Apache-2.0"), ["MIT", "Apache-2.0"]);
        assert_eq!(license_ids("MIT/Apache-2.0"), ["MIT", "Apache-2.0"]);
        assert_eq!(
            license_ids("(MIT OR Apache-2.0) AND Unicode-3.0"),
            ["MIT", "Apache-2.0", "Unicode-3.0"]
        );
        assert_eq!(
            license_ids("Apache-2.0 WITH LLVM-exception OR Apache-2.0 OR MIT"),
            ["Apache-2.0 WITH LLVM-exception", "Apache-2.0", "MIT"]
        );
    }
}
