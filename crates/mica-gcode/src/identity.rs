use mica_core::config::Config;
use std::{
    io,
    time::{SystemTime, UNIX_EPOCH},
};

pub const ORCA_VERSION: &str = "2.4.2";

/// Export time in seconds. A malformed SOURCE_DATE_EPOCH fails instead of silently
/// making a supposedly reproducible export depend on the wall clock.
pub fn epoch() -> io::Result<u64> {
    match std::env::var("SOURCE_DATE_EPOCH") {
        Ok(value) => value
            .parse::<u64>()
            .ok()
            .filter(|v| *v <= 253_402_300_799)
            .ok_or_else(|| {
                io::Error::new(
                    io::ErrorKind::InvalidInput,
                    "SOURCE_DATE_EPOCH must be seconds from 1970 through 9999",
                )
            }),
        Err(std::env::VarError::NotPresent) if mica_core::user_data::isolated() => Ok(0),
        Err(std::env::VarError::NotPresent) => Ok(SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs()),
        Err(_) => Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "SOURCE_DATE_EPOCH is not valid Unicode",
        )),
    }
}

/// Local wall time normally; fixed-epoch exports use UTC, independent of machine timezone.
pub fn timestamp() -> io::Result<String> {
    let secs = epoch()?;
    let at = jiff::Timestamp::from_second(secs as i64).map_err(io::Error::other)?;
    let zone = if fixed_epoch() {
        jiff::tz::TimeZone::UTC
    } else {
        jiff::tz::TimeZone::system()
    };
    Ok(at
        .to_zoned(zone)
        .strftime("%Y-%m-%d at %H:%M:%S")
        .to_string())
}

/// Whether the export time is fixed: SOURCE_DATE_EPOCH is set, or this is an isolated (test,
/// screenshot, monkey) process, where two exports must not differ only because the clock ticked.
fn fixed_epoch() -> bool {
    std::env::var_os("SOURCE_DATE_EPOCH").is_some() || mica_core::user_data::isolated()
}

/// Identity with an explicitly injected, already formatted timestamp.
pub fn line_at(config: &Config, timestamp: &str) -> String {
    if config.string("mica_gcode_identity") == Some("orca_compatible") {
        format!(
            "; generated by Mica Slicer {} (OrcaSlicer {ORCA_VERSION} on {timestamp})",
            mica_core::VERSION
        )
    } else {
        format!(
            "; generated by Mica Slicer {} on {timestamp}",
            mica_core::VERSION
        )
    }
}

pub fn line(config: &Config) -> io::Result<String> {
    Ok(line_at(config, &timestamp()?))
}

/// Which identity a Mica G-code file was written with (`mica` or `orca_compatible`), from
/// its first lines; `None` for files Mica did not write (or binary G-code).
pub fn of_text(head: &str) -> Option<&'static str> {
    let line = head
        .lines()
        .take(64)
        .find_map(|l| l.trim().strip_prefix("; generated by Mica Slicer "))?;
    Some(if line.contains("(OrcaSlicer ") {
        "orca_compatible"
    } else {
        "mica"
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn injected_identities() {
        let mut c = Config::defaults();
        let time = "1970-01-01 at 00:00:00";
        assert_eq!(
            line_at(&c, time),
            "; generated by Mica Slicer 0.0.1 on 1970-01-01 at 00:00:00"
        );
        c.set_raw("mica_gcode_identity", "orca_compatible").unwrap();
        assert_eq!(
            line_at(&c, time),
            "; generated by Mica Slicer 0.0.1 (OrcaSlicer 2.4.2 on 1970-01-01 at 00:00:00)"
        );
        assert_eq!(of_text(&line_at(&c, time)), Some("orca_compatible"));
        let plain = Config::defaults();
        assert_eq!(
            of_text(&format!("; HEADER\n{}\nG28\n", line_at(&plain, time))),
            Some("mica")
        );
        assert_eq!(
            of_text("; generated by OrcaSlicer 2.4.2 on 2026-10-20 at 10:00:00\n"),
            None
        );
    }
}
