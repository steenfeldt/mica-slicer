#[test]
fn structure_and_labels() {
    assert!(has(&report("M73 P50\nM73 P40"), "progress"));
    assert!(has(&report("M486 S0"), "object-label"));
    assert!(has(
        &report("EXCLUDE_OBJECT_START NAME=a\nEXCLUDE_OBJECT_END NAME=b"),
        "object-label"
    ));
    assert!(has(&report(";LAYER_CHANGE\n;Z:0.1"), "layer-order"));
    assert!(has(&report(";LAYER_CHANGE"), "layer-marker"));
    // Sequential printing: a two-layer object, a one-layer object, then a third object. The
    // head must rise above the taller one before travelling on (a short wipe may stay low).
    let first = "G1 X20 E0.3385\n;LAYER_CHANGE\n;Z:0.4\nG1 Z0.4\nG1 X30 E0.3\nG1 Z1\nG1 X100\n\
                 ;LAYER_CHANGE\n;Z:0.2\nG1 Z0.2\nG1 X120 E0.3\nG1 X121\n";
    let next = ";LAYER_CHANGE\n;Z:0.2\nG1 Z0.2\nG1 X170 E0.3";
    let sequence = |between: &str| report(&format!("{first}{between}{next}"));
    assert!(!has(&sequence("G1 Z1\nG1 X160\n"), "layer-order"));
    assert!(has(&sequence("G1 X160\n"), "layer-order"));
    assert!(has(&sequence("G1 Z1\nG1 Z0.3\nG1 X160\n"), "layer-order"));
    assert!(has(
        &report("G1 X20 E0.3385\n;LAYER_CHANGE\n;Z:0.1"),
        "layer-order"
    ));
    assert!(has(&validate_text(&b""[..], &profile()), "layers"));
}
