use super::*;
fn profile() -> Profile {
    let mut p = Profile::from_config(&Config::defaults()).unwrap();
    p.bed = vec![(0., 0.), (200., 0.), (200., 200.), (0., 200.)];
    p.max_z = 200.;
    p.bed_temperature = 60.;
    p.tools[0].min_temperature = 180.;
    p.tools[0].max_temperature = 250.;
    p
}

/// GUI monkey test (seed 1010): the U1 0.2 mm nozzle profile's start G-code (Orca's generic
/// toolchanger one) heats the bed in its Klipper macro, `PRINT_START … BED_TEMP=55`, and
/// OrcaSlicer writes no M140/M190 for Klipper. That bed is set and waited for.
#[test]
fn klipper_start_macro_heats_the_bed() {
    let mut p = profile();
    p.klipper = true;
    p.bed_temperature = 55.;
    p.tools[0].bed_temperature = 55.;
    let text = "; generated by test\nG90\nM83\nPRINT_START TOOL_TEMP=210 BED_TEMP=55 TOOL=0\nM104 S210\nM109 S210\nG1 X10 Y10 Z0.2\n;LAYER_CHANGE\n;Z:0.2\n;HEIGHT:0.2\n;TYPE:Perimeter\n;WIDTH:0.45\nG1 X20 E0.3385\nM73 P100\n";
    let r = validate_text(text.as_bytes(), &p);
    assert!(!has(&r, "bed-wait"), "{:?}", r.diagnostics);
    let r = validate_text(text.replace("BED_TEMP=55", "BED_TEMP=30").as_bytes(), &p);
    assert!(has(&r, "bed-wait"), "{:?}", r.diagnostics);
    // A Marlin printer's macro-looking line is not a bed command.
    p.klipper = false;
    let r = validate_text(text.as_bytes(), &p);
    assert!(has(&r, "bed-wait"), "{:?}", r.diagnostics);
}
fn program(body: &str) -> String {
    format!(
        "; generated by test\nG90\nM83\nM190 S60\nM109 S210\nG1 X10 Y10 Z0.2\n;LAYER_CHANGE\n;Z:0.2\n;HEIGHT:0.2\n;TYPE:Perimeter\n;WIDTH:0.45\n{body}\nM73 P100\n; filament used [mm] = 0.3385\n"
    )
}
fn report(body: &str) -> Report {
    validate_text(program(body).as_bytes(), &profile())
}
fn has(r: &Report, rule: &str) -> bool {
    r.diagnostics.iter().any(|d| d.rule == rule)
}
