/// Monkey-test regression: an XL plate whose first printing tool heats the bed to 90 °C while
/// tool 1's filament wants 105 °C, or a filament whose later layers run hotter than the first,
/// is correctly heated for the first layer. The bed wait follows the first printing tool's
/// first-layer temperature, not the hottest bed temperature of tool 1.
#[test]
fn bed_wait_follows_the_tool_that_prints_first() {
    let mut p = profile();
    p.tools.push(p.tools[0].clone());
    p.bed_temperature = 105.;
    p.tools[0].bed_temperature = 105.;
    p.tools[1].bed_temperature = 90.;
    let text = "; generated by test\nG90\nM83\nM190 S90\nM104 T1 S210\nT1\nM109 T1 S210\nG1 X10 Y10 Z0.2\n;LAYER_CHANGE\n;Z:0.2\n;HEIGHT:0.2\n;TYPE:Perimeter\n;WIDTH:0.45\nG1 X20 E0.3385\nM73 P100\n";
    let r = validate_text(text.as_bytes(), &p);
    assert!(!has(&r, "bed-wait"), "{:?}", r.diagnostics);
    // Starting on the tool whose filament wants 105 °C, 90 °C is not enough.
    let r = validate_text(text.replace("T1", "T0").as_bytes(), &p);
    assert!(has(&r, "bed-wait"), "{:?}", r.diagnostics);
    // GUI monkey test (seed 1008): on the XL the first wipe tower block (T1, for which the
    // start G-code heated the bed to 90 °C) and the tool change to T0 come before the first
    // layer marker; T0, whose filament wants 105 °C, then prints the first layer's perimeter.
    // The bed follows T1, the tool that printed first.
    let tower_first = text.replace(
        "G1 X10 Y10 Z0.2\n",
        "G1 X10 Y10 Z0.2\n;TYPE:Wipe tower\nG1 X30 E0.6\nT0\nM109 T0 S210\n",
    );
    let r = validate_text(tower_first.as_bytes(), &p);
    assert!(!has(&r, "bed-wait"), "{:?}", r.diagnostics);
    let r = validate_text(tower_first.replace("M190 S90", "M190 S60").as_bytes(), &p);
    assert!(has(&r, "bed-wait"), "{:?}", r.diagnostics);
}
#[test]
fn profile_temperature_below_its_recommended_range_warns_instead_of_failing() {
    // Polymaker's U1 PA presets print at 270 °C with a recommended 280–300 °C range.
    let mut c = Config::defaults();
    for (k, v) in [("temperature", "210"), ("first_layer_temperature", "210")] {
        c.set_raw(k, v).unwrap();
    }
    // Orca-only options arrive typed from the profile importer.
    for (k, v) in [
        ("nozzle_temperature_range_low", "220"),
        ("nozzle_temperature_range_high", "240"),
    ] {
        c.set(
            k,
            mica_core::config::parse_value(mica_core::config::OptType::Ints, v).unwrap(),
        );
    }
    let mut p = Profile::from_config(&c).unwrap();
    p.bed = profile().bed;
    p.max_z = 200.;
    p.bed_temperature = 60.;
    assert_eq!(p.tools[0].min_temperature, 210.);
    assert_eq!(p.tools[0].recommended_temperature, (220., 240.));
    let r = validate_text(program("G1 X20 E0.3385").as_bytes(), &p);
    assert!(!has(&r, "cold-extrusion"), "{:?}", r.diagnostics);
    assert!(has(&r, "filament-range"), "{:?}", r.diagnostics);
    // A commanded temperature below the profile's own is still cold extrusion.
    let r = validate_text(program("M104 S200\nG1 X20 E0.3385").as_bytes(), &p);
    assert!(has(&r, "cold-extrusion"), "{:?}", r.diagnostics);
}

/// GUI monkey test, seed 3011 (the XL under OrcaSlicer rules): a tool parked at the end
/// with its 20 mm toolchange retraction, written as a wipe (.69943 + .04252 + .03681 +
/// .02125, counted as 0.8 by Orca's unrounded bookkeeping) topped up by 19.2, is 20.00001 mm
/// retracted. The XL's filaments set that 20 mm (`filament_retract_length_toolchange`), so
/// the limit is twice that, and rounding of written moves is no imbalance.
#[test]
fn a_parked_tool_keeps_its_filament_toolchange_retraction() {
    let mut c = Config::defaults();
    c.set_raw("retract_length_toolchange", "10").unwrap();
    c.set_raw("filament_retract_length_toolchange", "20")
        .unwrap();
    assert_eq!(
        Profile::from_config(&c).unwrap().tools[0].retract_limit,
        40.
    );
    let parked = "G1 X20 E0.3385\nG1 E-.69943\nG1 X21 E-.04252\nG1 X22 E-.03681\nG1 X23 \
                  E-.02125\nG1 E-19.2";
    let mut p = profile();
    p.tools[0].retract_limit = 20.;
    let r = validate_text(program(parked).as_bytes(), &p);
    assert!(!has(&r, "retraction-balance"), "{:?}", r.diagnostics);
    // A real excess still counts.
    let r = validate_text(program(&format!("{parked}\nG1 E-.1")).as_bytes(), &p);
    assert!(has(&r, "retraction-balance"), "{:?}", r.diagnostics);
}

/// GUI monkey test (seed 703): on the XL, PrusaSlicer 2.9.6 (and Mica, which matches it) places
/// the timed preheat for a tool's next pick by time only. With short layers it can land in the
/// tool's own first-layer segment before its first extrusion, with the later-layer
/// `temperature`. The firmware heats while printing; the tool already waited at its first-layer
/// temperature. A preheat alone (no wait at a printing temperature) still owes the wait.
#[test]
fn xl_timed_preheat_of_the_waited_active_tool_owes_no_wait() {
    let ok = program("M104.1 T0 P60 Q62 S240\nG1 X20 E0.3385");
    let r = validate_text(ok.as_bytes(), &profile());
    assert!(!has(&r, "hotend-wait"), "{:?}", r.diagnostics);
    // The same target as plain M104 is one printing should have waited for.
    let plain = ok.replace("M104.1 T0 P60 Q62", "M104");
    let r = validate_text(plain.as_bytes(), &profile());
    assert!(has(&r, "hotend-wait"), "{:?}", r.diagnostics);
    // Waited only at an idle temperature: the preheat is no wait.
    let idle = ok.replace("M109 S210", "M109 S170");
    let r = validate_text(idle.as_bytes(), &profile());
    assert!(has(&r, "hotend-wait"), "{:?}", r.diagnostics);
    // Its target still counts for the temperature limits.
    let hot = ok.replace("S240", "S400");
    let r = validate_text(hot.as_bytes(), &profile());
    assert!(has(&r, "hot-extrusion"), "{:?}", r.diagnostics);
}
