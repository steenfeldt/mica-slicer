/// The U1 Benchy: OrcaSlicer's thick internal bridges report the bridge flow's height (the
/// 0.4 mm nozzle's diameter), outside the profile's 0.08-0.32 mm layer heights; that is the
/// flow's height, not a layer height. A perimeter that tall still warns.
#[test]
fn thick_bridges_report_their_flow_height_without_a_layer_height_warning() {
    let p = profile();
    let tall = p.max_layer + 0.08;
    for role in [
        "Internal Bridge",
        "Bridge infill",
        "Overhang perimeter",
        "Support transition",
    ] {
        let r = report(&format!(
            ";TYPE:{role}\n;WIDTH:.4\n;HEIGHT:{tall}\nG1 X20 E0.3385"
        ));
        assert_eq!(
            has(&r, "layer-height"),
            role == "Overhang perimeter",
            "{role}: {:?}",
            r.diagnostics
        );
    }
}
