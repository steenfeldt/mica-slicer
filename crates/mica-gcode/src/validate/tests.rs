#[test]
fn klipper_start_macros_heat_and_wait() {
    // Start macros are Klipper's; on a Marlin printer they are not heating commands.
    let mut p = profile();
    p.klipper = true;
    for start in [
        "START_PRINT EXTRUDER_TEMP=210 BED_TEMP=60 TOTAL_LAYER_COUNT=100",
        "PRINT_START BED=60 HOTEND=210",
    ] {
        let text = program("G1 X20 E0.3385").replace("M190 S60\nM109 S210", start);
        let r = validate_text(text.as_bytes(), &p);
        assert_eq!(r.errors, 0, "{start}: {:?}", r.diagnostics);
        assert!(has(&r, "start-macro"));
    }
    // A macro without temperatures waits for nothing.
    let text = program("G1 X20 E0.3385").replace("M190 S60\nM109 S210", "START_PRINT");
    let r = validate_text(text.as_bytes(), &p);
    assert!(has(&r, "cold-extrusion") || has(&r, "hotend-wait"));
}
