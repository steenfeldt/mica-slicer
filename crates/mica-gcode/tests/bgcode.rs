use mica_gcode::bgcode::*;

const BINARY: &[u8] = include_bytes!("fixtures/cube20_ps.bgcode");
const ASCII: &str = include_str!("fixtures/cube20_ps.gcode");

fn ini(metadata: &Metadata) -> &[(String, String)] {
    let Metadata::Ini(entries) = metadata else {
        panic!("expected INI")
    };
    entries
}

fn value<'a>(metadata: &'a Metadata, key: &str) -> &'a str {
    &ini(metadata).iter().find(|(k, _)| k == key).unwrap().1
}

/// Reconstruct Prusa's pre-MeatPack binary text from the independent ASCII run.
/// Only these explicitly checked sections are removed; all commands, full-line
/// comments, source inline comments and intervening blank lines remain intact.
fn binary_source() -> String {
    let (header, rest) = ASCII.split_once("\n\n").unwrap();
    assert_eq!(
        header,
        "; generated by PrusaSlicer 2.9.6 on 2026-10-15 at 19:30:58 UTC"
    );
    let (notes, rest) = rest
        .split_once("; external perimeters extrusion width")
        .unwrap();
    assert_eq!(notes, "; \n\n");
    let (widths, rest) = rest.split_once("\n\n").unwrap();
    // GCode.cpp emits these seven derived width summaries only in ASCII mode.
    // They are omitted, not relocated verbatim into metadata. The underlying
    // settings are present in the slicer config, checked below.
    assert_eq!(
        widths,
        concat!(
            " = 0.45mm\n",
            "; perimeters extrusion width = 0.45mm\n",
            "; infill extrusion width = 0.45mm\n",
            "; solid infill extrusion width = 0.45mm\n",
            "; top infill extrusion width = 0.42mm\n",
            "; support material extrusion width = 0.40mm\n",
            "; first layer extrusion width = 0.50mm"
        )
    );
    let (body, _) = rest.split_once("; objects_info = ").unwrap();
    // Both fixtures were CLI exports: there are NO thumbnail comment blocks or
    // binary thumbnail blocks, despite thumbnail sizes being in the profile.
    // Separate tests below exercise all three thumbnail formats.
    assert!(!ASCII.contains("; thumbnail begin"));
    assert!(!ASCII.contains("; thumbnail_QOI begin"));
    assert!(!ASCII.contains("; thumbnail_JPG begin"));
    format!("{notes}{body}")
}

#[test]
fn reference_ascii_text_and_metadata() {
    let decoded = decode(BINARY).unwrap();
    assert!(decoded.metadata.thumbnails.is_empty());
    let source = binary_source();
    // Independent text comparison, deliberately NOT using our MeatPack codec to
    // manufacture the expectation. This fixture's G lines already have canonical
    // uppercase parameters and single spaces. MeatPack removes inline comments,
    // blank lines and trailing spaces before inline comments; full comments stay.
    // No coordinate, extrusion, feedrate, progress or timing command is ignored.
    let expected: String = source
        .lines()
        .filter(|line| !line.trim().is_empty())
        .map(|line| {
            if line.trim_start().starts_with(';') {
                format!("{line}\n")
            } else {
                format!(
                    "{}\n",
                    line.split(';')
                        .next()
                        .unwrap()
                        .trim_end_matches([' ', '\t'])
                )
            }
        })
        .collect();
    assert_eq!(decoded.gcode, expected);
    assert_eq!(decoded.gcode.len(), 167360);

    // Only generation timestamps differ between the runs (19:30:58 vs 19:55:07).
    // Binary generation moves this header into file metadata, not G-code text.
    let file = decoded.metadata.file.as_ref().unwrap();
    assert_eq!(value(file, "Producer"), "PrusaSlicer 2.9.6");
    assert_eq!(value(file, "Produced on"), "2026-10-15 at 19:55:07 UTC");

    let (before_config, config) = ASCII.split_once("; prusaslicer_config = begin\n").unwrap();
    let (config, after_config) = config.split_once("; prusaslicer_config = end\n").unwrap();
    assert!(after_config.is_empty());
    let mut settings: Vec<(String, String)> = config
        .lines()
        .map(|line| {
            let (key, val) = line.strip_prefix("; ").unwrap().split_once(" = ").unwrap();
            (key.to_owned(), val.to_owned())
        })
        .collect();
    assert_eq!(settings.len(), 373);
    // The only setting changed for the two exports is the output format switch.
    let format = settings
        .iter_mut()
        .find(|(key, _)| key == "binary_gcode")
        .unwrap();
    assert_eq!(format.1, "0");
    format.1 = "1".into();
    assert_eq!(decoded.metadata.slicer, [Metadata::Ini(settings)]);

    let stats = &before_config[before_config.find("; objects_info = ").unwrap()..];
    let mut count = 0;
    for line in stats.lines().filter(|line| !line.is_empty()) {
        let (key, val) = line.strip_prefix("; ").unwrap().split_once(" = ").unwrap();
        let metadata = if key == "objects_info" {
            &decoded.metadata.printer
        } else {
            &decoded.metadata.print
        };
        assert_eq!(value(metadata, key), val, "relocated metadata: {key}");
        count += 1;
    }
    assert_eq!(count, 12);
    // This end-G-code comment is custom profile text and remains in BOTH files,
    // even though a separately formatted max_layer_z=20.00 is printer metadata.
    assert!(decoded.gcode.contains("; max_layer_z = 20\n"));
    assert_eq!(value(&decoded.metadata.printer, "max_layer_z"), "20.00");
}

#[test]
fn reference_blocks_crcs_round_trip_and_exact_heatshrink() {
    let decoded = decode(BINARY).unwrap();
    assert_eq!(decoded.checksum, Checksum::Crc32);
    let expected = [
        (BlockType::FileMetadata, Compression::None, 66, None),
        (BlockType::PrinterMetadata, Compression::None, 610, None),
        (
            BlockType::PrintMetadata,
            Compression::Deflate,
            392,
            Some(166),
        ),
        (
            BlockType::SlicerMetadata,
            Compression::Deflate,
            15237,
            Some(4933),
        ),
        (
            BlockType::Gcode,
            Compression::Heatshrink12_4,
            39761,
            Some(9054),
        ),
        (
            BlockType::Gcode,
            Compression::Heatshrink12_4,
            41553,
            Some(7095),
        ),
        (
            BlockType::Gcode,
            Compression::Heatshrink12_4,
            22780,
            Some(7134),
        ),
    ];
    assert_eq!(decoded.blocks.len(), expected.len());
    for (block, expected) in decoded.blocks.iter().zip(expected) {
        println!(
            "{:?}: {:?}, uncompressed={}, compressed={:?}",
            block.kind, block.compression, block.uncompressed_size, block.compressed_size
        );
        assert_eq!(
            (
                block.kind,
                block.compression,
                block.uncompressed_size,
                block.compressed_size
            ),
            expected
        );
    }

    let original_blocks: Vec<_> = decoded
        .blocks
        .iter()
        .filter(|b| b.kind == BlockType::Gcode)
        .collect();
    for (index, block) in original_blocks.iter().enumerate() {
        let original = &BINARY[block.payload_range.clone()];
        let packed = heatshrink::decode(
            original,
            heatshrink::Window::Bits12,
            block.uncompressed_size as usize,
        )
        .unwrap();
        assert_eq!(
            heatshrink::encode(&packed, heatshrink::Window::Bits12),
            original,
            "Heatshrink must reproduce every compressed byte of block {index}"
        );
        let text = &decoded.gcode[block.gcode_range.clone().unwrap()];
        let repacked = meatpack::encode(text, true);
        assert_eq!(meatpack::decode(&repacked).unwrap(), text);
        // Upstream unified_method appends a newline even when a G line already
        // has one. Inline-comment stripping removes the source newline first.
        // unbinarize suppresses duplicate newlines, so decoded text cannot reveal
        // which representation was used. Plain repacking gains 11 bytes in block
        // 0 and 1 byte in block 2; block 1 has no affected inline G comments.
        // This is an upstream non-invertibility, not a Heatshrink/window failure.
        // The next assertion group reconstructs original source comments and
        // boundaries and proves byte-exact MeatPack + Heatshrink for ALL blocks.
        assert_eq!(repacked.len() - packed.len(), [11, 0, 1][index]);
        if index == 1 {
            assert_eq!(repacked, packed);
        }
    }

    let rebuilt = encode(
        &binary_source(),
        &decoded.metadata,
        &BinarizerConfig::default(),
    )
    .unwrap();
    let rebuilt_decoded = decode(&rebuilt).unwrap();
    let rebuilt_blocks: Vec<_> = rebuilt_decoded
        .blocks
        .iter()
        .filter(|b| b.kind == BlockType::Gcode)
        .collect();
    assert_eq!(original_blocks.len(), rebuilt_blocks.len());
    for (original, rebuilt_block) in original_blocks.iter().zip(rebuilt_blocks) {
        assert_eq!(original.uncompressed_size, rebuilt_block.uncompressed_size);
        assert_eq!(
            &BINARY[original.payload_range.clone()],
            &rebuilt[rebuilt_block.payload_range.clone()]
        );
    }

    // Repacking decoded text changes source cache boundaries, but not its meaning,
    // text or metadata. Metadata comparisons preserve ordering and duplicate keys.
    let encoded = encode(
        &decoded.gcode,
        &decoded.metadata,
        &BinarizerConfig::default(),
    )
    .unwrap();
    let again = decode(&encoded).unwrap();
    assert_eq!(decoded.metadata, again.metadata);
    assert_eq!(decoded.gcode, again.gcode);
}

fn sample_metadata() -> BgcodeMetadata {
    let entries = Metadata::Ini(vec![
        ("key".into(), "a=b".into()),
        ("key".into(), "".into()),
    ]);
    BgcodeMetadata {
        file: Some(entries.clone()),
        printer: entries.clone(),
        print: entries.clone(),
        slicer: vec![
            entries,
            Metadata::Json("{\"version\":3,\"text\":\"å\"}".into()),
        ],
        thumbnails: [
            ThumbnailFormat::Png,
            ThumbnailFormat::Jpg,
            ThumbnailFormat::Qoi,
        ]
        .into_iter()
        .map(|format| Thumbnail {
            format,
            width: 16,
            height: 20,
            data: vec![0, 1, 2, 255, format as u8],
        })
        .collect(),
    }
}

#[test]
fn compression_encoding_checksum_matrix_and_thumbnails() {
    let metadata = sample_metadata();
    let text = "; comment å\n\nG1 X1 Y2 ; inline\nM104 S200\n";
    for compression in [
        Compression::None,
        Compression::Deflate,
        Compression::Heatshrink11_4,
        Compression::Heatshrink12_4,
    ] {
        for encoding in [
            GcodeEncoding::None,
            GcodeEncoding::MeatPack,
            GcodeEncoding::MeatPackComments,
        ] {
            for checksum in [Checksum::None, Checksum::Crc32] {
                let config = BinarizerConfig {
                    file_compression: compression,
                    printer_compression: compression,
                    print_compression: compression,
                    slicer_compression: compression,
                    gcode_compression: compression,
                    gcode_encoding: encoding,
                    checksum,
                    ..BinarizerConfig::default()
                };
                let encoded = encode(text, &metadata, &config).unwrap();
                let decoded = decode(&encoded).unwrap();
                let expected = match encoding {
                    GcodeEncoding::None => text,
                    GcodeEncoding::MeatPack => "G1 X1 Y2\nM104 S200\n",
                    GcodeEncoding::MeatPackComments => "; comment å\nG1 X1 Y2\nM104 S200\n",
                };
                assert_eq!(decoded.gcode, expected);
                assert_eq!(decoded.metadata, metadata);
                assert_eq!(decoded.checksum, checksum);
            }
        }
    }
}

#[test]
fn streaming_boundaries_empty_input_and_encoded_size_cap() {
    let metadata = sample_metadata();
    let config = BinarizerConfig {
        gcode_block_size: 12,
        ..BinarizerConfig::default()
    };
    let text = "G1 X1\nG1 X2\nG1 X3\n";
    let mut writer = Encoder::new(Vec::new(), &metadata, &config).unwrap();
    for line in text.split_inclusive('\n') {
        writer.append_gcode(line).unwrap();
    }
    let bytes = writer.finish().unwrap();
    assert_eq!(bytes, encode(text, &metadata, &config).unwrap());
    let decoded = decode(&bytes).unwrap();
    assert_eq!(decoded.gcode, text);
    assert_eq!(
        decoded
            .blocks
            .iter()
            .filter(|b| b.kind == BlockType::Gcode)
            .count(),
        2
    );
    assert!(
        decode(&encode("", &metadata, &config).unwrap())
            .unwrap()
            .gcode
            .is_empty()
    );
    assert!(encode("G1 X1", &metadata, &config).is_err());
    assert!(encode("G1 X123456789012345\n", &metadata, &config).is_err());
    assert!(
        encode(
            "",
            &metadata,
            &BinarizerConfig {
                gcode_block_size: 0,
                ..config
            }
        )
        .is_err()
    );

    // UTF-8 and unpackable M-line characters expand. Exercise the additional
    // encoded-size cap and its newline split without splitting a UTF-8 codepoint.
    let text = format!("M117 {}\n", "é".repeat(500)).repeat(100);
    let bytes = encode(&text, &metadata, &BinarizerConfig::default()).unwrap();
    let decoded = decode(&bytes).unwrap();
    assert_eq!(decoded.gcode, text);
    assert!(
        decoded
            .blocks
            .iter()
            .filter(|b| b.kind == BlockType::Gcode)
            .all(|block| block.uncompressed_size <= MAX_GCODE_BLOCK_SIZE as u32)
    );
    let oversized = format!("M117 {}\n", "m".repeat(50000));
    assert!(encode(&oversized, &metadata, &BinarizerConfig::default()).is_err());
}

#[test]
fn corruption_truncation_unknown_fields_and_limits() {
    let decoded = decode(BINARY).unwrap();
    for block in &decoded.blocks {
        // CRC covers header sizes, parameters, payload and the checksum itself.
        for index in [
            block.offset + 4,
            block.payload_range.start - 1,
            block.payload_range.start,
            block.payload_range.end,
        ] {
            let mut bad = BINARY.to_vec();
            bad[index] ^= 1;
            assert!(
                matches!(decode(&bad), Err(Error::Checksum { .. })),
                "corruption at {index}"
            );
        }
        for end in [
            block.offset + 1,
            block.payload_range.start - 1,
            block.payload_range.end + 3,
        ] {
            assert!(decode(&BINARY[..end]).is_err(), "truncation at {end}");
        }
    }
    for index in [0, 4, 8, 10, 12] {
        let mut bad = BINARY.to_vec();
        bad[index] = 255;
        assert!(decode(&bad).is_err());
    }
    let mut trailing = BINARY.to_vec();
    trailing.push(0);
    assert!(decode(&trailing).is_err());
    assert!(decode(b"GCDE\x01\0\0\0\x01\0").is_err());
    assert!(matches!(
        decode_with_limits(
            BINARY,
            DecodeLimits {
                max_block_bytes: 100,
                max_total_bytes: 1000000
            }
        ),
        Err(Error::LimitExceeded)
    ));
    assert!(matches!(
        decode_with_limits(
            BINARY,
            DecodeLimits {
                max_block_bytes: 1000000,
                max_total_bytes: 100
            }
        ),
        Err(Error::LimitExceeded)
    ));
}

#[test]
fn malformed_metadata_order_and_compressed_streams() {
    let metadata = sample_metadata();
    let config = BinarizerConfig {
        checksum: Checksum::None,
        ..BinarizerConfig::default()
    };
    let bytes = encode("G1 X0\n", &metadata, &config).unwrap();
    let decoded = decode(&bytes).unwrap();
    let mut bad = bytes.clone();
    bad[10..12].copy_from_slice(&(BlockType::Gcode as u16).to_le_bytes());
    assert!(decode(&bad).is_err());
    let print = decoded
        .blocks
        .iter()
        .find(|b| b.kind == BlockType::PrintMetadata)
        .unwrap();
    for delta in [-1i64, 1] {
        let mut bad = bytes.clone();
        bad[print.offset + 4..print.offset + 8]
            .copy_from_slice(&((print.uncompressed_size as i64 + delta) as u32).to_le_bytes());
        assert!(decode(&bad).is_err());
    }
    let mut bad = bytes.clone();
    bad[print.payload_range.start] = 0;
    assert!(decode(&bad).is_err());
    // A size-correct zlib stream followed by junk must also be rejected.
    let mut bad = bytes.clone();
    bad.insert(print.payload_range.end, 0);
    bad[print.offset + 8..print.offset + 12]
        .copy_from_slice(&(print.compressed_size.unwrap() + 1).to_le_bytes());
    assert!(decode(&bad).is_err());
    let mut no_file = metadata.clone();
    no_file.file = None;
    assert_eq!(
        decode(&encode("", &no_file, &config).unwrap())
            .unwrap()
            .metadata,
        no_file
    );
    let mut invalid = metadata.clone();
    invalid.print = Metadata::Ini(vec![("a=b".into(), "v".into())]);
    assert!(encode("", &invalid, &config).is_err());
    invalid = metadata;
    invalid.thumbnails[0].width = 0;
    assert!(encode("", &invalid, &config).is_err());
}

#[test]
fn streaming_propagates_io_errors() {
    struct FailingWriter;
    impl std::io::Write for FailingWriter {
        fn write(&mut self, _: &[u8]) -> std::io::Result<usize> {
            Err(std::io::Error::other("test failure"))
        }
        fn flush(&mut self) -> std::io::Result<()> {
            Ok(())
        }
    }
    assert!(matches!(
        Encoder::new(
            FailingWriter,
            &sample_metadata(),
            &BinarizerConfig::default()
        ),
        Err(Error::Io(_))
    ));
}
