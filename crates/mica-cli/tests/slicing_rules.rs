//! `mica_slicing_rules`: one explicit switch picks PrusaSlicer's or OrcaSlicer's behaviour,
//! independent of the firmware's G-code flavor (docs/slicing-rules.md).
//!
//! - A CORE One (Marlin 2) sliced like OrcaSlicer takes the Orca path (Orca cooling and fan
//!   markers, Orca's travel lift incl. Auto Lift, Orca's seam placer) and validates.
//! - A Klipper printer (the U1) sliced like PrusaSlicer takes the Prusa path and still writes
//!   Klipper's commands.
//! - Orca-only options set on a CORE One under PrusaSlicer rules no longer change anything
//!   (merged settings such as scarf seams apply under both: merged_settings.rs).

use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};

static NEXT: AtomicU64 = AtomicU64::new(0);

fn model(name: &str) -> String {
    format!("{}/../../tests/models/{name}", env!("CARGO_MANIFEST_DIR"))
}

fn out() -> PathBuf {
    std::env::temp_dir().join(format!(
        "mica-rules-{}-{}.gcode",
        std::process::id(),
        NEXT.fetch_add(1, Ordering::Relaxed)
    ))
}

const CORE_ONE: &[&str] = &[
    "--printer",
    "Prusa CORE One HF0.4 nozzle",
    "--print",
    "0.20mm SPEED @COREONE HF0.4",
    "--filament",
    "Prusament PLA @COREONE HF0.4",
];
const U1: &[&str] = &[
    "--vendor",
    "Snapmaker",
    "--printer",
    "Snapmaker U1 (0.4 nozzle)",
    "--print",
    "0.20 Standard @Snapmaker U1 (0.4 nozzle)",
    "--filament",
    "Snapmaker PLA @U1",
    "--bed",
    "High Temp Plate",
];

fn args(list: &[&str]) -> Vec<String> {
    list.iter().map(|s| s.to_string()).collect()
}

/// `mica slice <model> <profile> <extra>`, or `None` when the profiles are not installed.
fn slice(file: &str, profile: &[&str], extra: &[&str]) -> Option<String> {
    let path = out();
    let mut all = args(&["slice", &model(file)]);
    all.extend(args(profile));
    all.extend(args(extra));
    all.extend(["-o".into(), path.to_string_lossy().into_owned()]);
    if !mica_testkit::require_profiles_for(&all) {
        return None;
    }
    match mica_cli::run(&all) {
        Ok(()) => {}
        Err(e) => panic!("mica {all:?}: {e}"),
    }
    // The validator (0 errors, else `run` fails) with the same profile.
    let mut validate = args(&["validate", &path.to_string_lossy()]);
    validate.extend(args(profile));
    validate.extend(args(extra));
    mica_cli::run(&validate).unwrap_or_else(|e| panic!("validate {extra:?}: {e}"));
    let text = std::fs::read_to_string(&path).unwrap();
    let _ = std::fs::remove_file(&path);
    Some(without_settings_block(text))
}

/// The G-code without its timestamped identity line and its trailing full-settings block (which
/// lists every setting, including ones that don't change the print), so comparisons here are
/// about the printed result.
fn without_settings_block(mut text: String) -> String {
    for start in ["; prusaslicer_config = begin", "; CONFIG_BLOCK_START"] {
        if let Some(at) = text.find(start) {
            text.truncate(at);
        }
    }
    text.lines()
        .filter(|l| !l.starts_with("; generated by "))
        .map(|l| format!("{l}\n"))
        .collect()
}

#[test]
fn core_one_sliced_like_orcaslicer_takes_the_orca_path() {
    let Some(prusa) = slice("hole_block.stl", CORE_ONE, &[]) else {
        return;
    };
    let orca = slice(
        "hole_block.stl",
        CORE_ONE,
        &["--slicing-rules", "orcaslicer"],
    )
    .unwrap();
    assert_ne!(prusa, orca);
    // Orca's CoolingBuffer markers and fan handling, as on the U1 path.
    assert!(orca.contains(";_SET_FAN_SPEED_CHANGING_LAYER"));
    assert!(!prusa.contains(";_SET_FAN_SPEED_CHANGING_LAYER"));
    // Still Marlin 2 / Prusa firmware commands: no Klipper macros.
    for klipper in [
        "EXCLUDE_OBJECT",
        "SET_VELOCITY_LIMIT",
        "SET_PRESSURE_ADVANCE",
    ] {
        assert!(!orca.contains(klipper), "{klipper}");
    }
    // Orca's Z-hop types (here Auto Lift, the U1's) drive the travel lift.
    let auto = slice(
        "hole_block.stl",
        CORE_ONE,
        &[
            "--slicing-rules",
            "orcaslicer",
            "--set",
            "z_hop_types=Auto Lift",
        ],
    )
    .unwrap();
    let normal = slice(
        "hole_block.stl",
        CORE_ONE,
        &[
            "--slicing-rules",
            "orcaslicer",
            "--set",
            "z_hop_types=Normal Lift",
        ],
    )
    .unwrap();
    assert_ne!(auto, normal);
    // Orca's seam placer: Orca's scarf seams take effect.
    let scarf = slice(
        "hole_block.stl",
        CORE_ONE,
        &[
            "--slicing-rules",
            "orcaslicer",
            "--set",
            "seam_slope_type=all",
        ],
    )
    .unwrap();
    assert_ne!(scarf, orca);
    // `--set mica_slicing_rules=…` is the same switch.
    let set = slice(
        "hole_block.stl",
        CORE_ONE,
        &["--set", "mica_slicing_rules=orcaslicer"],
    )
    .unwrap();
    assert_eq!(set, orca);
}

#[test]
fn klipper_printer_sliced_like_prusaslicer_keeps_klipper_commands() {
    let Some(orca) = slice("cube20.stl", U1, &[]) else {
        return;
    };
    let prusa = slice("cube20.stl", U1, &["--slicing-rules", "prusaslicer"]).unwrap();
    assert_ne!(orca, prusa);
    // The Prusa path: no Orca cooling markers, PrusaSlicer's fan-off at the end.
    assert!(orca.contains(";_SET_FAN_SPEED_CHANGING_LAYER"));
    assert!(!prusa.contains(";_SET_FAN_SPEED_CHANGING_LAYER"));
    assert!(prusa.contains("M107\n;TYPE:Custom"));
    // Klipper's commands stay: firmware follows gcode_flavor.
    for klipper in [
        "EXCLUDE_OBJECT_DEFINE",
        "EXCLUDE_OBJECT_START",
        "SET_VELOCITY_LIMIT",
    ] {
        assert!(prusa.contains(klipper), "{klipper}");
    }
}

#[test]
fn orca_options_do_not_change_a_core_one_sliced_like_prusaslicer() {
    let Some(base) = slice("hole_block.stl", CORE_ONE, &[]) else {
        return;
    };
    // (Scarf seams and the wall order are merged settings that apply under both rules:
    // tests/merged_settings.rs.)
    for set in [
        "scarf_joint_speed=40%",
        "scarf_joint_flow_ratio=0.8",
        "support_remove_small_overhang=1",
        "bridge_line_width=100%",
        "z_hop_types=Spiral Lift",
    ] {
        let with = slice("hole_block.stl", CORE_ONE, &["--set", set]).unwrap();
        assert!(
            with == base,
            "{set} changed the G-code under PrusaSlicer rules"
        );
    }
}
