//! Exercise the actual CLI process with a fixed export clock and isolated user settings.
use std::{path::PathBuf, process::Command};

#[test]
fn u1_identity_and_effective_native_settings() {
    if !std::path::Path::new(
        "/Applications/OrcaSlicer.app/Contents/Resources/profiles/Snapmaker.json",
    )
    .exists()
    {
        return;
    }
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let dir = std::env::temp_dir().join(format!("mica-gcode-config-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let run = |extra: &[&str], name: &str| {
        let output = dir.join(name);
        let result = Command::new(env!("CARGO_BIN_EXE_mica"))
            .env("MICA_CONFIG_DIR", dir.join("settings"))
            .env("SOURCE_DATE_EPOCH", "0")
            .args(["slice"])
            .arg(root.join("tests/models/cube20.stl"))
            .args([
                "--vendor",
                "Snapmaker",
                "--printer",
                "Snapmaker U1 (0.4 nozzle)",
                "--print",
                "0.20 Standard @Snapmaker U1 (0.4 nozzle)",
                "--filament",
                "Snapmaker PLA @U1",
                "--bed",
                "High Temp Plate",
            ])
            .args(extra)
            .arg("-o")
            .arg(&output)
            .output()
            .unwrap();
        assert!(
            result.status.success(),
            "{}",
            String::from_utf8_lossy(&result.stderr)
        );
        std::fs::read_to_string(output).unwrap()
    };
    let a = run(&[], "default.gcode");
    assert!(a.contains(concat!(
        "; generated by Mica Slicer ",
        env!("CARGO_PKG_VERSION"),
        " (OrcaSlicer 2.4.2 on 1970-01-01 at 00:00:00)\n"
    )));
    assert_eq!(a, run(&[], "repeat.gcode"));
    let config = a.split_once("; CONFIG_BLOCK_START\n").unwrap().1;
    assert!(config.contains("; sparse_infill_density = 15%\n"));
    assert!(config.contains("; initial_layer_travel_speed = 100%\n"));
    assert!(config.contains("; filament_end_gcode = ;;;\n"));
    assert!(!config.contains("; perimeters ="));
    let b = run(
        &[
            "--gcode-identity",
            "mica",
            "--set",
            "perimeters=3",
            "--set",
            "external_perimeter_speed=123",
        ],
        "edited.gcode",
    );
    assert!(b.contains(concat!(
        "; generated by Mica Slicer ",
        env!("CARGO_PKG_VERSION"),
        " on 1970-01-01 at 00:00:00\n"
    )));
    let config = b.split_once("; CONFIG_BLOCK_START\n").unwrap().1;
    assert!(config.contains("; wall_loops = 3\n"));
    assert!(config.contains("; outer_wall_speed = 123\n"));
    assert!(config.contains("; initial_layer_travel_speed = 100%\n"));
    let bad = Command::new(env!("CARGO_BIN_EXE_mica"))
        .env("MICA_CONFIG_DIR", dir.join("settings"))
        .args(["slice"])
        .arg(root.join("tests/models/cube20.stl"))
        .args(["--gcode-identity", "fake"])
        .output()
        .unwrap();
    assert!(!bad.status.success());
    std::fs::remove_dir_all(dir).unwrap();
}

#[test]
fn exported_orca_option_inventory_matches_both_pins() {
    let mut schema = std::collections::BTreeMap::<String, serde_json::Value>::new();
    for text in [
        include_str!("../../mica-profiles/src/orca/snapmaker-orca_schema.json"),
        include_str!("../../mica-profiles/src/orca/orca_schema.json"),
    ] {
        schema.extend(
            serde_json::from_str::<std::collections::BTreeMap<String, serde_json::Value>>(text)
                .unwrap(),
        );
    }
    let expected: String = schema
        .iter()
        .map(|(k, v)| {
            format!(
                "{}\t{}\t{}\n",
                k,
                v["type"].as_str().unwrap(),
                u8::from(v["nullable"] == true)
            )
        })
        .collect();
    let actual: String = include_str!("../../mica-gcode/src/orca_gcode_options.tsv")
        .lines()
        .filter(|l| !l.starts_with('#'))
        .map(|l| format!("{l}\n"))
        .collect();
    assert_eq!(
        actual, expected,
        "regenerate the G-code inventory from both schema JSON files"
    );
}
