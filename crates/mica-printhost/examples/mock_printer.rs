/// The slicer Moonraker's metadata parser names for an uploaded G-code file (the multipart
/// body), from its `; generated by …` line. Legacy: only the fixed list older Moonraker forks
/// know; modern: any `NAME VERSION on …` (upstream Moonraker since 4637d70).
fn slicer_of(body: &[u8], legacy: bool) -> String {
    let head = String::from_utf8_lossy(&body[..body.len().min(65_536)]);
    let Some(line) = head
        .lines()
        .find_map(|l| l.trim().strip_prefix("; generated by "))
    else {
        return "Unknown".into();
    };
    const KNOWN: [&str; 9] = [
        "PrusaSlicer",
        "SuperSlicer",
        "OrcaSlicer",
        "BambuStudio",
        "Cura_SteamEngine",
        "Simplify3D",
        "KISSlicer",
        "ideaMaker",
        "Kiri:Moto",
    ];
    // `NAME VERSION on`, the NAME possibly inside parentheses (an alias line).
    for name in KNOWN {
        if let Some(at) = line.find(&format!("{name} "))
            && line[at + name.len() + 1..].contains(" on ")
        {
            return name.into();
        }
    }
    if legacy {
        return "Unknown".into();
    }
    let Some(on) = line.find(" on ") else {
        return "Unknown".into();
    };
    match line[..on].rsplit_once(' ') {
        Some((name, _version)) if !name.is_empty() => name.into(),
        _ => "Unknown".into(),
    }
}

/// A job file's preview picture: the part (a block in the given colour, three shaded faces) on
/// a light grey ground, 300 × 300 RGB, like a slicer's thumbnail.
fn job_thumbnail(part: [f64; 3]) -> mica_camera::mock::Rgb {
    const S: usize = 300;
    let mut rgb = vec![0u8; S * S * 3];
    for y in 0..S {
        for x in 0..S {
            let (fx, fy) = (x as f64 - 150., y as f64 - 150.);
            // An isometric box: the top rhombus, then the left and right faces below it.
            let (cy, half_h, height) = (-50., 58., 100.);
            let edge = 1. - fx.abs() / 100.;
            let lower = cy + half_h * edge;
            let shade = if edge < 0. {
                None
            } else if (fy - cy).abs() <= half_h * edge {
                Some(1.)
            } else if fy > lower && fy <= lower + height {
                Some(if fx < 0. { 0.78 } else { 0.6 })
            } else {
                None
            };
            let c = match shade {
                Some(s) => [part[0] * s, part[1] * s, part[2] * s],
                None => [214., 216., 220.],
            };
            let i = (y * S + x) * 3;
            rgb[i] = c[0].clamp(0., 255.) as u8;
            rgb[i + 1] = c[1].clamp(0., 255.) as u8;
            rgb[i + 2] = c[2].clamp(0., 255.) as u8;
        }
    }
    mica_camera::mock::Rgb {
        width: S as u32,
        height: S as u32,
        data: rgb,
    }
}

/// Part colours of the fake camera pictures.
const U1_PART: [f64; 3] = [255., 125., 56.];
const CORE_ONE_PART: [f64; 3] = [46., 196., 166.];
const XL_PART: [f64; 3] = [130., 110., 255.];

/// A fake camera frame: a dark enclosure, the bed, a part growing with the job's progress
/// and a slowly moving highlight so successive frames differ. 320 × 240 RGB.
fn camera_frame(sim: &Sim, t: f64, part: [f64; 3]) -> mica_camera::mock::Rgb {
    const W: usize = 320;
    const H: usize = 240;
    let mut rgb = vec![0u8; W * H * 3];
    let progress = sim.fraction();
    let part_h = if matches!(sim.state, State::Idle) {
        0.
    } else {
        progress * 90.
    };
    for y in 0..H {
        for x in 0..W {
            let (fx, fy) = (x as f64 / W as f64, y as f64 / H as f64);
            // Vignetted dark grey background with a faint warm light from the top.
            let d = ((fx - 0.5).powi(2) + (fy - 0.4).powi(2)).sqrt();
            let base = (70. - d * 70.).max(18.);
            let mut c = [base * 1.05, base, base * 0.95];
            // Bed: a lighter trapezoid in the lower half.
            if fy > 0.62 && fy < 0.9 {
                let spread = 0.1 + (fy - 0.62) * 0.3;
                if fx > 0.5 - spread - 0.2 && fx < 0.5 + spread + 0.2 {
                    c = [92., 96., 102.];
                    // Printed perimeters on the sheet.
                    if ((x / 6) % 2 == 0) && fy > 0.64 && fy < 0.66 {
                        c = [120., 124., 130.];
                    }
                }
            }
            // The part: a block centred on the bed, growing upwards.
            let bottom = 0.72 * H as f64;
            let top = bottom - part_h;
            if (y as f64) > top && (y as f64) < bottom && fx > 0.41 && fx < 0.59 {
                let shade = 0.75 + 0.25 * (fx - 0.41) / 0.18;
                c = [part[0] * shade, part[1] * shade, part[2] * shade];
                if (y as f64 - top) < 2. {
                    c = [
                        (part[0] + 255.) / 2.,
                        (part[1] + 255.) / 2.,
                        (part[2] + 255.) / 2.,
                    ];
                }
            }
            // A moving highlight (the toolhead's shadow sweeping).
            let sweep = 0.5 + 0.35 * (t * 0.8).sin();
            if (fx - sweep).abs() < 0.015 && fy > 0.3 && fy < 0.62 {
                c = [c[0] * 0.6, c[1] * 0.6, c[2] * 0.6];
            }
            let i = (y * W + x) * 3;
            rgb[i] = c[0].clamp(0., 255.) as u8;
            rgb[i + 1] = c[1].clamp(0., 255.) as u8;
            rgb[i + 2] = c[2].clamp(0., 255.) as u8;
        }
    }
    mica_camera::mock::Rgb {
        width: W as u32,
        height: H as u32,
        data: rgb,
    }
}

/// The XL's "IP camera": `/snapshot.jpg` (one JPEG) and `/stream.mjpg` (MJPEG), no login.
fn ip_camera(port: u16, sim: Arc<Mutex<Sim>>) -> thread::JoinHandle<()> {
    let listener = TcpListener::bind(("127.0.0.1", port))
        .unwrap_or_else(|e| panic!("cannot bind 127.0.0.1:{port}: {e}"));
    println!("XL camera (snapshot / MJPEG): http://127.0.0.1:{port}/snapshot.jpg, /stream.mjpg");
    let started = Instant::now();
    thread::spawn(move || {
        for stream in listener.incoming() {
            let Ok(stream) = stream else { continue };
            let sim = sim.clone();
            thread::spawn(move || {
                let Ok(mut writer) = stream.try_clone() else {
                    return;
                };
                let mut reader = BufReader::new(stream);
                while let Some(request) = read_request(&mut reader, false) {
                    let path = request.path.split('?').next().unwrap_or("");
                    if path == "/stream.mjpg" {
                        let s = sim.clone();
                        let render: mica_camera::mock::Renderer =
                            Arc::new(move |t| camera_frame(&s.lock().unwrap(), t, XL_PART));
                        mica_camera::mock::serve_mjpeg(&mut writer, &render, 10.);
                        return;
                    }
                    let (code, body) = if path == "/snapshot.jpg" {
                        let frame = {
                            let mut s = sim.lock().unwrap();
                            s.tick();
                            camera_frame(&s, started.elapsed().as_secs_f64(), XL_PART)
                        };
                        (200, mica_camera::mock::jpeg(&frame, 80))
                    } else {
                        (404, vec![])
                    };
                    let head = format!(
                        "HTTP/1.1 {code} {}\r\nContent-Type: image/jpeg\r\nContent-Length: {}\r\nConnection: keep-alive\r\n\r\n",
                        reason(code),
                        body.len()
                    );
                    if writer.write_all(head.as_bytes()).is_err()
                        || writer.write_all(&body).is_err()
                    {
                        return;
                    }
                }
            });
        }
    })
}
