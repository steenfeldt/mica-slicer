/// What [`synthetic_library`] wrote.
#[derive(Debug, Default, Clone)]
pub struct Synthetic {
    pub files: usize,
    /// Files whose content duplicates another file's.
    pub duplicates: usize,
    /// Pictures and documents (not counted in `files`).
    pub extras: usize,
    pub bytes: u64,
}

/// Builds a synthetic library of `n` model files under `dest`: mostly unique generated STL
/// shapes, copies of the repository's test models and projects (duplicates), OBJ, STEP and
/// G-code files, plus a hidden `.git` folder the scan must skip.
pub fn synthetic_library(dest: &Path, n: usize) -> std::io::Result<Synthetic> {
    synthetic_range(dest, 0..n)
}

/// Like [`synthetic_library`] for the file numbers in `range` (other ranges give other
/// generated content, so two folders can hold different models).
pub fn synthetic_range(dest: &Path, range: std::ops::Range<usize>) -> std::io::Result<Synthetic> {
    let models = repo_root().join("tests/models");
    let real: Vec<(String, Vec<u8>)> = [
        "3DBenchy.stl",
        "cube20.stl",
        "hole_block.stl",
        "shells.stl",
        "taper.stl",
        "thin_features.stl",
        "painted-cube.3mf",
        "plates-orca.3mf",
    ]
    .iter()
    .filter_map(|f| Some((f.to_string(), std::fs::read(models.join(f)).ok()?)))
    .collect();
    let mut out = Synthetic::default();
    let write = |rel: String, bytes: &[u8], out: &mut Synthetic| -> std::io::Result<()> {
        let p = dest.join(rel);
        std::fs::create_dir_all(p.parent().unwrap_or(dest))?;
        std::fs::write(&p, bytes)?;
        out.files += 1;
        out.bytes += bytes.len() as u64;
        Ok(())
    };
    let printers = [
        "Prusa CORE One HF0.4 nozzle",
        "Original Prusa XL - 5T Input Shaper 0.4 nozzle",
        "Snapmaker U1 (0.4 nozzle)",
    ];
    let mut seen_real = std::collections::HashSet::new();
    let mut copies = 0;
    for i in range {
        let folder = FOLDERS[i % FOLDERS.len()];
        let word = WORDS[(i * 7 + i / FOLDERS.len()) % WORDS.len()];
        let f = (i % 20) as f32;
        match i % 20 {
            // Copies of the real test models and projects: the duplicates.
            0 | 7 | 13 => {
                let (name, bytes) = &real[(copies * 3) % real.len()];
                copies += 1;
                if !seen_real.insert(name.clone()) {
                    out.duplicates += 1;
                }
                write(format!("{folder}/{i:04}-{name}"), bytes, &mut out)?;
            }
            1 | 11 => {
                let printer = printers[i % printers.len()];
                let colours: &[&str] = if i % 3 == 0 {
                    &["#8B7CF6", "#F2A65A", "#56B45B"]
                } else {
                    &["#E5534B"]
                };
                let grams: Vec<f64> = colours.iter().map(|_| 2. + i as f64 * 0.01).collect();
                write(
                    format!("{folder}/{word}-{i:04}.gcode"),
                    &sample_gcode(printer, colours, &grams),
                    &mut out,
                )?;
            }
            5 => write(
                format!("{folder}/{word}-{i:04}.bgcode"),
                &sample_bgcode(printers[1], 600. + i as f64),
                &mut out,
            )?,
            9 => write(
                format!("{folder}/{word}-{i:04}.obj"),
                &obj_text(&mesh_edit::sphere(4. + (i % 37) as f32 * 0.5, 8, 12)),
                &mut out,
            )?,
            17 => write(
                format!("{folder}/{word}-{i:04}.step"),
                format!("ISO-10303-21;\nHEADER;\n/* {word} {i} */\nENDSEC;\nEND-ISO-10303-21;\n")
                    .as_bytes(),
                &mut out,
            )?,
            k => {
                // Unique generated shapes (their sizes depend on `i`).
                let s = 5. + (i % 97) as f32 * 0.7;
                let mesh = match k % 3 {
                    0 => mesh_edit::cuboid([s, 10. + f, 4. + (i % 13) as f32]),
                    1 => mesh_edit::cylinder(s * 0.5, 8. + (i % 17) as f32, 16 + i % 24),
                    _ => mesh_edit::merge(&[
                        &mesh_edit::cuboid([s, s, 3.]),
                        &mesh_edit::transformed(
                            &mesh_edit::cylinder(3., 12. + f, 20),
                            &[
                                [1., 0., 0., s * 0.5],
                                [0., 1., 0., s * 0.5],
                                [0., 0., 1., 3.],
                                [0., 0., 0., 1.],
                            ],
                        ),
                    ]),
                };
                write(
                    format!("{folder}/{word}-{i:04}.stl"),
                    &stl_bytes(&mesh),
                    &mut out,
                )?;
            }
        }
    }
    // Never indexed: version control and hidden folders, AppleDouble files, other types.
    write(
        ".git/objects/cube.stl".into(),
        b"solid x\nendsolid x\n",
        &mut Synthetic::default(),
    )?;
    write(
        "Toys/._resource-fork.stl".into(),
        b"\0\0",
        &mut Synthetic::default(),
    )?;
    write(
        "Toys/readme.txt".into(),
        b"not a model",
        &mut Synthetic::default(),
    )?;
    Ok(out)
}

/// A rendered picture of `mesh` in `colour`, `px` square, as PNG (pictures next to models).
pub fn picture_png(mesh: &TriangleMesh, px: u16, colour: [u8; 3]) -> Vec<u8> {
    let img =
        mica_gcode::thumbnails::render(mesh, px, px, colour, mica_gcode::thumbnails::Camera::Prusa)
            .expect("render");
    mica_gcode::thumbnails::encode_png(u32::from(img.width), u32::from(img.height), &img.rgba)
        .expect("png")
}

/// The same picture as JPEG (photos people take of their prints are mostly JPEG).
pub fn picture_jpeg(mesh: &TriangleMesh, px: u16, colour: [u8; 3]) -> Vec<u8> {
    let img =
        mica_gcode::thumbnails::render(mesh, px, px, colour, mica_gcode::thumbnails::Camera::Prusa)
            .expect("render");
    // JPEG has no alpha: put the render on a light background.
    let mut rgb = Vec::with_capacity(img.rgba.len() / 4 * 3);
    for p in img.rgba.chunks(4) {
        let a = u32::from(p[3]);
        for c in &p[..3] {
            rgb.push(((u32::from(*c) * a + 236 * (255 - a)) / 255) as u8);
        }
    }
    let mut out = vec![];
    image::codecs::jpeg::JpegEncoder::new_with_quality(&mut out, 85)
        .encode(
            &rgb,
            u32::from(img.width),
            u32::from(img.height),
            image::ExtendedColorType::Rgb8,
        )
        .expect("jpeg");
    out
}

/// An OrcaSlicer project with known colours: the repository's `plates-orca.3mf` (filament
/// colours `#CB8F29`, `#000000`, `#FFFFFF`, `#FB0207`; on plate 1 a cube on tool 1 with a
/// side painted tool 2 and one tool 3, and a cube on tool 2) plus Orca's default yellow
/// `extruder_colour` for every extruder, as Orca writes it.
pub fn coloured_3mf() -> Vec<u8> {
    use std::io::{Read, Write};
    let src = std::fs::read(repo_root().join("tests/models/plates-orca.3mf")).expect("test 3MF");
    let mut zin = zip::ZipArchive::new(std::io::Cursor::new(src)).expect("zip");
    let mut out = zip::ZipWriter::new(std::io::Cursor::new(Vec::new()));
    let opts = zip::write::SimpleFileOptions::default()
        .compression_method(zip::CompressionMethod::Deflated);
    for i in 0..zin.len() {
        let mut f = zin.by_index(i).expect("entry");
        let name = f.name().to_string();
        let mut data = vec![];
        f.read_to_end(&mut data).expect("read entry");
        if name == "Metadata/project_settings.config" {
            let mut v: serde_json::Value = serde_json::from_slice(&data).expect("json");
            v["extruder_colour"] = serde_json::json!(["#FCE94F", "#FCE94F", "#FCE94F", "#FCE94F"]);
            data = serde_json::to_vec_pretty(&v).expect("json");
        }
        out.start_file(name, opts).expect("entry");
        out.write_all(&data).expect("write entry");
    }
    out.finish().expect("zip").into_inner()
}

/// A project 3MF: the repository's `plates-orca.3mf` with `picture` as its plate thumbnail
/// (so each generated project has its own content and cover).
pub fn sample_3mf(picture: &[u8]) -> Vec<u8> {
    use std::io::{Read, Write};
    let src = std::fs::read(repo_root().join("tests/models/plates-orca.3mf")).expect("test 3MF");
    let mut zin = zip::ZipArchive::new(std::io::Cursor::new(src)).expect("zip");
    let mut out = zip::ZipWriter::new(std::io::Cursor::new(Vec::new()));
    let opts = zip::write::SimpleFileOptions::default()
        .compression_method(zip::CompressionMethod::Deflated);
    for i in 0..zin.len() {
        let mut f = zin.by_index(i).expect("entry");
        if f.name().eq_ignore_ascii_case("Metadata/plate_1.png") {
            continue;
        }
        let name = f.name().to_string();
        let mut data = vec![];
        f.read_to_end(&mut data).expect("read entry");
        out.start_file(name, opts).expect("entry");
        out.write_all(&data).expect("write entry");
    }
    out.start_file("Metadata/plate_1.png", opts).expect("entry");
    out.write_all(picture).expect("write entry");
    out.finish().expect("zip").into_inner()
}

/// Builds a few realistic downloads under `dest` (each a folder as a model site's "download
/// all" gives it: parts, an assembled 3MF project, sliced G-code, pictures, a readme and a
/// license), plus a loose duplicate of one part and, optionally, a big folder of unrelated
/// models:
///
/// - `Downloads/Articulated_Dragon-model_files/`: `files/` with 10 STL parts (the two legs
///   identical), `Articulated_Dragon.3mf`, a G-code, `images/cover.png`, `README.txt`,
///   `LICENSE.txt`
/// - `Downloads/Cable Organizer - 5123456/`: 3 STL parts, `cable organizer.3mf`, `photo.jpg`
/// - `Downloads/Desk Hook/`: `desk-hook.stl` and `desk-hook.bgcode`
/// - `Toys/dragon head.stl`: the same content as the dragon's head part
/// - with `collection` > 0, `STL Collection/` with that many unrelated models
pub fn synthetic_downloads(dest: &Path, collection: usize) -> std::io::Result<Synthetic> {
    let mut out = Synthetic::default();
    let write = |rel: &str, bytes: &[u8], out: &mut Synthetic| -> std::io::Result<()> {
        let p = dest.join(rel);
        std::fs::create_dir_all(p.parent().unwrap_or(dest))?;
        std::fs::write(&p, bytes)?;
        if crate::model::Kind::of(&p).is_some() {
            out.files += 1;
        } else {
            out.extras += 1;
        }
        out.bytes += bytes.len() as u64;
        Ok(())
    };
    let at = |m: &TriangleMesh, x: f32, y: f32, z: f32| {
        mesh_edit::transformed(
            m,
            &[
                [1., 0., 0., x],
                [0., 1., 0., y],
                [0., 0., 1., z],
                [0., 0., 0., 1.],
            ],
        )
    };
    // The dragon: ten parts, assembled in the 3MF.
    let dragon = "Downloads/Articulated_Dragon-model_files";
    let parts: Vec<(&str, TriangleMesh)> = vec![
        ("head", mesh_edit::sphere(9., 10, 16)),
        ("jaw", mesh_edit::cuboid([14., 8., 4.])),
        ("body_1", mesh_edit::cylinder(8., 14., 24)),
        ("body_2", mesh_edit::cylinder(7., 14., 24)),
        ("body_3", mesh_edit::cylinder(6., 14., 24)),
        ("tail", mesh_edit::cylinder(3., 30., 16)),
        ("wing_left", mesh_edit::cuboid([40., 18., 2.])),
        ("wing_right", mesh_edit::cuboid([40., 18., 2.4])),
        ("leg_left", mesh_edit::cuboid([5., 5., 16.])),
        ("leg_right", mesh_edit::cuboid([5., 5., 16.])),
    ];
    for (name, m) in &parts {
        write(
            &format!("{dragon}/files/{name}.stl"),
            &stl_bytes(m),
            &mut out,
        )?;
    }
    write("Toys/dragon head.stl", &stl_bytes(&parts[0].1), &mut out)?;
    out.duplicates += 2;
    let assembled = mesh_edit::merge(&[
        &at(&parts[0].1, 0., 0., 24.),
        &at(&parts[2].1, 12., 0., 8.),
        &at(&parts[3].1, 24., 0., 6.),
        &at(&parts[5].1, 36., 0., 4.),
        &at(&parts[6].1, 4., 10., 20.),
        &at(&parts[8].1, 10., -4., 0.),
        &at(&parts[9].1, 24., -4., 0.),
    ]);
    write(
        &format!("{dragon}/Articulated_Dragon.3mf"),
        &sample_3mf(&picture_png(&assembled, 256, [0xe5, 0x53, 0x4b])),
        &mut out,
    )?;
    write(
        &format!("{dragon}/Articulated_Dragon_0.4n_0.2mm_PLA_COREONE_3h12m.gcode"),
        &sample_gcode(
            "Prusa CORE One HF0.4 nozzle",
            &["#E5534B", "#F2A65A"],
            &[31., 4.],
        ),
        &mut out,
    )?;
    write(
        &format!("{dragon}/images/cover.png"),
        &picture_png(&assembled, 256, [0x56, 0xb4, 0x5b]),
        &mut out,
    )?;
    write(
        &format!("{dragon}/README.txt"),
        b"Articulated dragon. Print the parts, then snap the body segments together.\n",
        &mut out,
    )?;
    write(
        &format!("{dragon}/LICENSE.txt"),
        b"Creative Commons Attribution 4.0\n",
        &mut out,
    )?;
    // A cable organizer: three parts, a project and a photo.
    let cable = "Downloads/Cable Organizer - 5123456";
    let clip = mesh_edit::merge(&[
        &mesh_edit::cuboid([30., 12., 3.]),
        &at(&mesh_edit::cylinder(4., 10., 20), 8., 6., 3.),
        &at(&mesh_edit::cylinder(4., 10., 20), 22., 6., 3.),
    ]);
    let base = mesh_edit::cuboid([60., 20., 4.]);
    let cap = mesh_edit::cylinder(6., 3., 28);
    for (name, m) in [("clip", &clip), ("base", &base), ("cap", &cap)] {
        write(&format!("{cable}/{name}.stl"), &stl_bytes(m), &mut out)?;
    }
    let whole = mesh_edit::merge(&[&base, &at(&clip, 15., 4., 4.)]);
    write(
        &format!("{cable}/cable organizer.3mf"),
        &sample_3mf(&picture_png(&whole, 256, [0x8b, 0x7c, 0xf6])),
        &mut out,
    )?;
    write(
        &format!("{cable}/photo.jpg"),
        &picture_jpeg(&whole, 320, [0x3f, 0x8f, 0xd2]),
        &mut out,
    )?;
    // A hook and its G-code.
    let hook = mesh_edit::merge(&[
        &mesh_edit::cuboid([20., 4., 40.]),
        &mesh_edit::cuboid([20., 25., 4.]),
    ]);
    write(
        "Downloads/Desk Hook/desk-hook.stl",
        &stl_bytes(&hook),
        &mut out,
    )?;
    write(
        "Downloads/Desk Hook/desk-hook.bgcode",
        &sample_bgcode("Original Prusa XL - 5T Input Shaper 0.4 nozzle", 1500.),
        &mut out,
    )?;
    // A big folder of unrelated models: a collection, not one project.
    for i in 0..collection {
        let word = WORDS[(i * 3) % WORDS.len()];
        let s = 6. + (i % 89) as f32 * 0.9;
        let m = if i % 2 == 0 {
            mesh_edit::cuboid([s, 8. + (i % 7) as f32, 3. + (i % 11) as f32])
        } else {
            mesh_edit::cylinder(s * 0.4, 6. + (i % 13) as f32, 12 + i % 20)
        };
        write(
            &format!("STL Collection/{word}-{i:05}.stl"),
            &stl_bytes(&m),
            &mut out,
        )?;
    }
    Ok(out)
}
