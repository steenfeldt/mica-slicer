//! Helpers for tests, the GUI screenshots, the monkey test and the scan benchmark: temporary
//! folders and a synthetic model library built from the repository's own test models plus
//! generated shapes and G-code. Nothing here touches the user's folders.

use mica_core::mesh::TriangleMesh;
use mica_core::mesh_edit;
use std::path::{Path, PathBuf};

/// A temporary folder, removed (with everything in it) when dropped.
pub struct TempDir(PathBuf);

impl TempDir {
    pub fn new(tag: &str) -> TempDir {
        use std::sync::atomic::{AtomicU64, Ordering};
        static N: AtomicU64 = AtomicU64::new(0);
        let p = std::env::temp_dir().join(format!(
            "mica-library-{tag}-{}-{}-{}",
            std::process::id(),
            N.fetch_add(1, Ordering::Relaxed),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map_or(0, |d| d.as_nanos())
        ));
        std::fs::create_dir_all(&p).expect("create temp dir");
        // Canonical, so paths match what file-system events report (`/private/var/…`).
        TempDir(std::fs::canonicalize(&p).unwrap_or(p))
    }
    pub fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

/// The repository root (for `tests/models`).
pub fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("repo root")
        .to_path_buf()
}

fn stl_bytes(mesh: &TriangleMesh) -> Vec<u8> {
    let mut out = vec![];
    mesh_edit::write_stl(mesh, "mica", &mut out).expect("write to memory");
    out
}

fn thumbnail_png(mesh: &TriangleMesh, px: u16) -> Vec<u8> {
    let img = mica_gcode::thumbnails::render(
        mesh,
        px,
        px,
        [0xf2, 0xa6, 0x5a],
        mica_gcode::thumbnails::Camera::Prusa,
    )
    .expect("render");
    mica_gcode::thumbnails::encode_png(u32::from(img.width), u32::from(img.height), &img.rgba)
        .expect("png")
}

fn base64(data: &[u8]) -> String {
    const A: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut s = String::new();
    for c in data.chunks(3) {
        let n = (u32::from(c[0]) << 16)
            | (u32::from(*c.get(1).unwrap_or(&0)) << 8)
            | u32::from(*c.get(2).unwrap_or(&0));
        for i in 0..4 {
            if i <= c.len() {
                s.push(A[(n >> (18 - 6 * i) & 63) as usize] as char);
            } else {
                s.push('=');
            }
        }
    }
    s
}

/// A small PrusaSlicer-style text G-code: a thumbnail block at the top, a few moves, and
/// the metadata block at the end (1 h 2 m 3 s, `grams` per tool).
pub fn sample_gcode(printer: &str, colours: &[&str], grams: &[f64]) -> Vec<u8> {
    let png = thumbnail_png(&mesh_edit::cylinder(8., 20., 24), 64);
    let b64 = base64(&png);
    let mut g = String::from("; generated by Mica Slicer (library test)\n\n");
    g += &format!("; thumbnail begin 64x64 {}\n", b64.len());
    for line in b64.as_bytes().chunks(78) {
        g += &format!("; {}\n", std::str::from_utf8(line).unwrap_or(""));
    }
    g += "; thumbnail end\n\nG28\nG1 X10 Y10 Z0.2 F3000\nG1 X20 E1\n\n";
    let list = |v: &[f64]| {
        v.iter()
            .map(|x| format!("{x:.2}"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    g += &format!(
        "; filament used [mm] = {}\n",
        list(&grams.iter().map(|g| g * 330.).collect::<Vec<_>>())
    );
    g += &format!("; filament used [g] = {}\n", list(grams));
    g += &format!(
        "; total filament used [g] = {:.2}\n",
        grams.iter().sum::<f64>()
    );
    g += "; estimated printing time (normal mode) = 1h 2m 3s\n\n; prusaslicer_config = begin\n";
    g += &format!("; printer_settings_id = {printer}\n");
    g += "; print_settings_id = 0.20mm SPEED\n";
    g += &format!(
        "; filament_settings_id = {}\n",
        colours
            .iter()
            .map(|_| "\"Prusament PLA\"")
            .collect::<Vec<_>>()
            .join(";")
    );
    g += &format!("; filament_colour = {}\n", colours.join(";"));
    g += "; prusaslicer_config = end\n";
    g.into_bytes()
}

/// A small binary G-code with printer metadata, a QOI thumbnail and `time_s` of printing.
pub fn sample_bgcode(printer: &str, time_s: f64) -> Vec<u8> {
    use mica_gcode::bgcode::{
        BgcodeMetadata, BinarizerConfig, Metadata, Thumbnail, ThumbnailFormat, encode,
    };
    let img = mica_gcode::thumbnails::render(
        &mesh_edit::cuboid([20., 10., 5.]),
        32,
        32,
        [0x56, 0xb4, 0x5b],
        mica_gcode::thumbnails::Camera::Prusa,
    )
    .expect("render");
    let qoi = mica_gcode::thumbnails::encode_qoi(32, 32, &img.rgba).expect("qoi");
    let s = time_s as u64;
    let time = format!("{}m {}s", s / 60, s % 60);
    let meta = BgcodeMetadata {
        file: Some(Metadata::Ini(vec![("Producer".into(), "Mica test".into())])),
        printer: Metadata::Ini(vec![
            ("printer_model".into(), "XL5".into()),
            ("filament used [g]".into(), "2.50".into()),
            ("estimated printing time (normal mode)".into(), time),
        ]),
        thumbnails: vec![Thumbnail {
            format: ThumbnailFormat::Qoi,
            width: 32,
            height: 32,
            data: qoi,
        }],
        print: Metadata::Ini(vec![("filament used [mm]".into(), "830.00".into())]),
        slicer: vec![Metadata::Ini(vec![
            ("printer_settings_id".into(), printer.into()),
            ("filament_colour".into(), "#FF8000".into()),
        ])],
    };
    encode("G28\nG1 X1 Y1\n", &meta, &BinarizerConfig::default()).expect("bgcode")
}

fn obj_text(mesh: &TriangleMesh) -> Vec<u8> {
    let mut s = String::from("# Mica library test\n");
    for v in &mesh.vertices {
        s += &format!("v {} {} {}\n", v[0], v[1], v[2]);
    }
    for f in &mesh.faces {
        s += &format!("f {} {} {}\n", f[0] + 1, f[1] + 1, f[2] + 1);
    }
    s.into_bytes()
}

