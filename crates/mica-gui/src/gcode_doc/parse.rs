//! Reads an existing G-code file into the preview's disk-backed records (`preview.bin` /
//! `attrs.bin` in a temporary job folder), so an opened `.gcode` / `.bgcode` shows exactly like
//! a slice: layers, extrusion paths with their feature roles (PrusaSlicer's and Orca's `;TYPE:`
//! names), tools, travel, fan, temperature, acceleration and planned speed.
//!
//! Two streaming passes, neither holding the file: [`scan`] collects the metadata (header and
//! configuration comments, `M862` printer checks, the feature names in use, footer statistics,
//! `M73` times) and [`parse`] turns the moves into records, one layer buffered at a time. A
//! binary file is decoded block by block into the job folder first ([`decode_binary`]).

