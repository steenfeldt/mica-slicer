/// Longest line read; longer ones (a malformed or binary file) are an error.
const MAX_LINE: usize = 1 << 20;
/// Records buffered per layer before they are planned and written (bounds memory for files
/// without layer tags, or vase-mode layers).
const LAYER_CHUNK: usize = 1 << 18;
/// Footer comment lines kept for the statistics.
const TAIL_LINES: usize = 600;

/// What the metadata pass found.
#[derive(Clone, Debug, Default)]
pub struct Scan {
    /// `; generated by …` without the prefix (`PrusaSlicer 2.9.6 on …`).
    pub generator: Option<String>,
    /// `; key = value` comments (header, configuration block) and binary metadata, first
    /// occurrence wins.
    pub values: BTreeMap<String, String>,
    /// `M862.3 P "COREONE"`: the printer model the file checks for.
    pub printer_check: Option<String>,
    /// `M862.1 P0.4`: the nozzle the file checks for (`0.4`, `HF0.4` for a high-flow one).
    pub nozzle_check: Option<String>,
    /// Every `;TYPE:` name in the file.
    pub types: BTreeSet<String>,
    /// The last comment lines (the statistics footer).
    pub tail: Vec<String>,
    /// The largest `M73 … R<minutes>` (normal mode): the file's own print time estimate.
    pub m73_minutes: Option<f64>,
    /// `;LAYER_CHANGE` tags.
    pub layer_tags: usize,
    pub lines: usize,
    /// Lines that are moves (`G0`–`G3`).
    pub moves: usize,
    /// Lines that are neither empty, comments nor commands: more than a few means the file is
    /// not G-code.
    pub garbage: usize,
    /// The file was binary G-code (`GCDE`).
    pub binary: bool,
}

impl Scan {
    /// The footer's own print time (`; estimated printing time (normal mode) = 1h 2m 3s`,
    /// Orca's `; total estimated time: …`), else the largest `M73 R`.
    pub fn file_time_s(&self) -> Option<f64> {
        let footer = self.tail.iter().rev().find_map(|l| {
            let l = l.trim_start_matches(';').trim();
            let rest = l
                .strip_prefix("estimated printing time (normal mode) =")
                .or_else(|| l.strip_prefix("total estimated time:"))
                .or_else(|| l.strip_prefix("estimated printing time ="))?;
            parse_duration(rest.trim())
        });
        footer.or(self.m73_minutes.map(|m| m * 60.))
    }
    /// The statistics footer as text (`worker::per_tool_filament` reads it).
    pub fn tail_text(&self) -> String {
        self.tail.join("\n")
    }
    /// A footer statistic: `; key = value` among the last comment lines.
    pub fn footer(&self, key: &str) -> Option<&str> {
        self.tail.iter().rev().find_map(|l| {
            let (k, v) = l.trim_start_matches(';').split_once(" = ")?;
            (k.trim() == key).then(|| v.trim())
        })
    }
}

/// `1d 2h 3m 4s`, `3h 8m 31s`, `45s` → seconds.
pub fn parse_duration(text: &str) -> Option<f64> {
    let mut total = 0.;
    let mut any = false;
    for part in text.split_whitespace() {
        let (number, unit) = part.split_at(part.find(|c: char| c.is_alphabetic())?);
        let v: f64 = number.parse().ok()?;
        total += v * match unit {
            "d" => 86400.,
            "h" => 3600.,
            "m" => 60.,
            "s" => 1.,
            _ => return None,
        };
        any = true;
    }
    any.then_some(total)
}

/// Why a file cannot be shown, in words for the notification.
#[derive(Clone, Debug, PartialEq)]
pub struct Invalid(pub String);

impl std::fmt::Display for Invalid {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

/// Reads lines as bytes (no UTF-8 requirement, bounded length), calling `line` for each.
/// `progress` gets the bytes read so far; returning `false` from `line` stops early.
fn each_line(
    mut reader: impl BufRead,
    cancel: &AtomicBool,
    mut progress: impl FnMut(u64),
    mut line: impl FnMut(&[u8]) -> Result<(), Invalid>,
) -> Result<(), Invalid> {
    let mut buffer = Vec::with_capacity(256);
    let mut read = 0u64;
    let mut next_report = 0u64;
    loop {
        buffer.clear();
        let n = reader
            .by_ref()
            .take(MAX_LINE as u64 + 1)
            .read_until(b'\n', &mut buffer)
            .map_err(|e| Invalid(format!("Mica could not read the file: {e}")))?;
        if n == 0 {
            return Ok(());
        }
        if buffer.len() > MAX_LINE {
            return Err(Invalid(
                "This is not a G-code file: it has a line longer than 1 MB".into(),
            ));
        }
        read += n as u64;
        if read >= next_report {
            if cancel.load(Ordering::Relaxed) {
                return Err(Invalid("Canceled".into()));
            }
            progress(read);
            next_report = read + (1 << 20);
        }
        let mut l = buffer.as_slice();
        while let [rest @ .., b'\n' | b'\r'] = l {
            l = rest;
        }
        line(l)?;
    }
}

fn trim(b: &[u8]) -> &[u8] {
    b.trim_ascii()
}

/// Whether a line looks like G-code: a command word (`G1`, `M104`, `T0`), a Klipper macro
/// (`PRINT_START`, `SET_VELOCITY_LIMIT`), or a comment.
fn is_code(l: &[u8]) -> bool {
    match l.first() {
        None | Some(b';') => true,
        Some(c) if c.is_ascii_alphabetic() => {
            let word: &[u8] = l
                .split(|c| c.is_ascii_whitespace() || *c == b';')
                .next()
                .unwrap_or(l);
            let upper = word.iter().all(|c| {
                c.is_ascii_uppercase() || c.is_ascii_digit() || matches!(c, b'_' | b'.' | b'-')
            });
            let command = word.len() >= 2
                && word[0].is_ascii_alphabetic()
                && word[1..].iter().all(|c| c.is_ascii_digit() || *c == b'.');
            command || upper
        }
        _ => false,
    }
}

/// The metadata pass over a text G-code file.
pub fn scan(
    reader: impl BufRead,
    cancel: &AtomicBool,
    progress: impl FnMut(u64),
) -> Result<Scan, Invalid> {
    let mut s = Scan::default();
    let mut tail: VecDeque<String> = VecDeque::new();
    each_line(reader, cancel, progress, |raw| {
        s.lines += 1;
        let l = trim(raw);
        if l.contains(&0) {
            return Err(Invalid(
                "This is not a G-code file: it contains binary data".into(),
            ));
        }
        if let Some(comment) = l.strip_prefix(b";") {
            let text = String::from_utf8_lossy(comment);
            let t = text.trim();
            if let Some(name) = t.strip_prefix("TYPE:") {
                if !s.types.contains(name) {
                    s.types.insert(name.trim().to_string());
                }
                return Ok(());
            }
            if t == "LAYER_CHANGE" {
                s.layer_tags += 1;
                return Ok(());
            }
            if let Some(g) = t.strip_prefix("generated by ")
                && s.generator.is_none()
            {
                s.generator = Some(g.trim().to_string());
            }
            if let Some((k, v)) = t.split_once(" = ").or_else(|| t.split_once(": "))
                && !k.is_empty()
                && k.len() < 80
                && k.bytes().all(|c| {
                    c.is_ascii_alphanumeric()
                        || matches!(c, b'_' | b' ' | b'[' | b']' | b'(' | b')')
                })
            {
                if v.len() < 4096 && !s.values.contains_key(k.trim()) {
                    s.values.insert(k.trim().to_string(), v.trim().to_string());
                }
                if tail.len() == TAIL_LINES {
                    tail.pop_front();
                }
                tail.push_back(format!("; {}", t));
            }
            return Ok(());
        }
        if l.is_empty() {
            return Ok(());
        }
        if !is_code(l) {
            s.garbage += 1;
            if s.garbage > 50 && s.garbage * 4 > s.lines {
                return Err(Invalid(
                    "This is not a G-code file: most of its lines are not G-code commands".into(),
                ));
            }
            return Ok(());
        }
        match word(l) {
            (b'G', 0..=3) => s.moves += 1,
            (b'M', 73) => {
                // Normal mode only (Prusa's `M73 Q… S…` is the silent mode).
                if let Some(r) = param(l, b'R')
                    && param(l, b'P').is_some()
                    && r.is_finite()
                {
                    s.m73_minutes = Some(s.m73_minutes.map_or(r, |m: f64| m.max(r)));
                }
            }
            (b'M', 862) => {
                let text = String::from_utf8_lossy(l);
                let code = text.split(';').next().unwrap_or("").trim();
                if let Some(rest) = code.strip_prefix("M862.3") {
                    if let Some(p) = rest.trim().strip_prefix('P') {
                        s.printer_check
                            .get_or_insert_with(|| p.trim().trim_matches('"').to_string());
                    }
                } else if let Some(rest) = code.strip_prefix("M862.1") {
                    // `F1`: a high-flow nozzle (PrusaSlicer's `HF0.4` variants).
                    let hf = rest.split_whitespace().any(|w| w == "F1");
                    if let Some(p) = rest.split_whitespace().find_map(|w| w.strip_prefix('P')) {
                        s.nozzle_check
                            .get_or_insert_with(|| format!("{}{p}", if hf { "HF" } else { "" }));
                    }
                }
            }
            _ => {}
        }
        Ok(())
    })?;
    s.tail = tail.into();
    if s.moves == 0 {
        return Err(Invalid(if s.lines == 0 {
            "The file is empty".into()
        } else {
            "This file has no moves: there is nothing to print or preview".into()
        }));
    }
    Ok(s)
}

/// Decodes a binary G-code file into `out` (text), adding its metadata to `scan`. Returns
/// the text file's size.
pub fn decode_binary(
    path: &Path,
    out: &Path,
    cancel: &AtomicBool,
    mut progress: impl FnMut(u64),
) -> Result<BTreeMap<String, String>, Invalid> {
    use mica_gcode::bgcode::{self, stream::Block};
    let file =
        File::open(path).map_err(|e| Invalid(format!("Mica could not read the file: {e}")))?;
    let total = file.metadata().map(|m| m.len()).unwrap_or(0);
    let mut writer = BufWriter::new(
        File::create(out).map_err(|e| Invalid(format!("Mica could not unpack the file: {e}")))?,
    );
    // Counts compressed bytes through the reader for the progress bar.
    struct Counting<R> {
        inner: R,
        read: Arc<std::sync::atomic::AtomicU64>,
    }
    impl<R: Read> Read for Counting<R> {
        fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
            let n = self.inner.read(buf)?;
            self.read.fetch_add(n as u64, Ordering::Relaxed);
            Ok(n)
        }
    }
    let read = Arc::new(std::sync::atomic::AtomicU64::new(0));
    let reader = BufReader::new(Counting {
        inner: file,
        read: read.clone(),
    });
    let mut values = BTreeMap::new();
    let mut failure: Option<Invalid> = None;
    let result = bgcode::stream::visit(reader, 64 * 1024 * 1024, |block| {
        if cancel.load(Ordering::Relaxed) {
            failure = Some(Invalid("Canceled".into()));
            return Err(bgcode::Error::Invalid("canceled"));
        }
        progress(read.load(Ordering::Relaxed).min(total));
        match block {
            Block::Metadata(_, bgcode::Metadata::Ini(entries)) => {
                for (k, v) in entries {
                    values.entry(k.trim().to_string()).or_insert(v);
                }
            }
            Block::Metadata(..) | Block::Thumbnail(_) => {}
            Block::Gcode(text) => {
                if let Err(e) = writer.write_all(text.as_bytes()) {
                    failure = Some(Invalid(format!("Mica could not unpack the file: {e}")));
                    return Err(bgcode::Error::Invalid("write failed"));
                }
            }
        }
        Ok(())
    });
    if let Some(f) = failure {
        return Err(f);
    }
    result.map_err(|e| Invalid(format!("This binary G-code file is damaged: {e}")))?;
    writer
        .flush()
        .map_err(|e| Invalid(format!("Mica could not unpack the file: {e}")))?;
    Ok(values)
}

/// The command word of a line: (`G`, 1) for `G1 X…`, (`M`, 104), (`T`, 2). Unknown → (0, 0).
/// `G28.1`-style sub-codes keep only the integer part.
fn word(l: &[u8]) -> (u8, u32) {
    let Some(&letter) = l.first() else {
        return (0, 0);
    };
    let letter = letter.to_ascii_uppercase();
    if !matches!(letter, b'G' | b'M' | b'T') {
        return (0, 0);
    }
    let digits = l[1..].iter().take_while(|c| c.is_ascii_digit()).count();
    if digits == 0 || digits > 6 {
        return (0, 0);
    }
    // `TIMELAPSE_STOP` is a macro, not `T`.
    if let Some(&c) = l.get(1 + digits)
        && !(c.is_ascii_whitespace() || c == b';' || c == b'.')
    {
        return (0, 0);
    }
    let n = std::str::from_utf8(&l[1..1 + digits])
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(0);
    (letter, n)
}

/// The value of parameter `p` in a command line (`X12.5`, `S210`), ignoring the comment.
fn param(l: &[u8], p: u8) -> Option<f64> {
    let code = l.split(|c| *c == b';').next().unwrap_or(l);
    let mut words = code.split(|c| c.is_ascii_whitespace());
    words.next();
    for w in words {
        if let Some((&first, rest)) = w.split_first()
            && first.to_ascii_uppercase() == p
        {
            return std::str::from_utf8(rest).ok()?.parse().ok();
        }
    }
    None
}

/// A Klipper `KEY=value` parameter of a macro line.
fn macro_param(l: &[u8], key: &str) -> Option<f64> {
    let text = std::str::from_utf8(l).ok()?;
    let code = text.split(';').next()?;
    code.split_whitespace().find_map(|w| {
        let (k, v) = w.split_once('=')?;
        k.eq_ignore_ascii_case(key)
            .then(|| v.parse().ok())
            .flatten()
    })
}

/// Preview role (`Role as u32`) of a `;TYPE:` name, PrusaSlicer's and Orca's. `None`: Custom
/// G-code or a name Mica does not know (they share the "unknown" slot).
pub fn role_of(name: &str) -> Option<u32> {
    use mica_core::toolpath::Role::*;
    Some(match name.trim() {
        // PrusaSlicer.
        "Perimeter" => Perimeter as u32,
        "External perimeter" => ExternalPerimeter as u32,
        "Overhang perimeter" => OverhangPerimeter as u32,
        "Internal infill" => InternalInfill as u32,
        "Solid infill" => SolidInfill as u32,
        "Top solid infill" => TopSolidInfill as u32,
        "Ironing" => Ironing as u32,
        "Bridge infill" => BridgeInfill as u32,
        "Gap fill" => GapFill as u32,
        "Skirt" | "Skirt/Brim" => Skirt as u32,
        "Support material" => SupportMaterial as u32,
        "Support material interface" => SupportMaterialInterface as u32,
        "Wipe tower" => TOWER,
        // Orca (and Bambu / Snapmaker).
        "Inner wall" => Perimeter as u32,
        "Outer wall" => ExternalPerimeter as u32,
        "Overhang wall" => OverhangPerimeter as u32,
        "Sparse infill" => InternalInfill as u32,
        "Internal solid infill" | "Bottom surface" => SolidInfill as u32,
        "Top surface" => TopSolidInfill as u32,
        "Bridge" => BridgeInfill as u32,
        "Internal Bridge" => InternalBridgeInfill as u32,
        "Gap infill" => GapFill as u32,
        "Brim" => Brim as u32,
        "Support" | "Support transition" => SupportMaterial as u32,
        "Support interface" => SupportMaterialInterface as u32,
        "Prime tower" => TOWER,
        "Floating vertical shell" => SolidInfill as u32,
        _ => return None,
    })
}

/// The slot "unknown" extrusions use: the first of a preference list the file's own types
/// leave free (gap fill's white first), and its label.
pub fn unknown_slot(types: &BTreeSet<String>) -> (u32, &'static str) {
    use mica_core::toolpath::Role::*;
    let used: BTreeSet<u32> = types.iter().filter_map(|t| role_of(t)).collect();
    // PrusaSlicer's and Orca's own `Custom` G-code (purge lines) keeps its name; a file
    // without feature types, or with names Mica does not know, shows them as unknown.
    let label = if types.is_empty() || types.iter().any(|t| role_of(t).is_none() && t != "Custom") {
        "Unknown"
    } else {
        "Custom"
    };
    let slot = [
        GapFill,
        Ironing,
        InternalBridgeInfill,
        Brim,
        OverhangPerimeter,
        SupportMaterialInterface,
        SupportMaterial,
        BridgeInfill,
        TopSolidInfill,
        Skirt,
    ]
    .into_iter()
    .map(|r| r as u32)
    .find(|r| !used.contains(r))
    .unwrap_or(GapFill as u32);
    (slot, label)
}

