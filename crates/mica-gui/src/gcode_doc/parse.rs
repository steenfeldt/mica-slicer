/// One layer's records being collected.
#[derive(Default)]
struct LayerBuf {
    segments: Vec<Segment>,
    moves: Vec<Move>,
    temps: Vec<f64>,
    z: Option<f32>,
    extrusions: usize,
    /// Records of this layer already written (a chunked layer).
    written: bool,
}

struct State<'a> {
    builder: Builder,
    options: &'a Options,
    layer: LayerBuf,
    /// Positions (mm): X Y Z E.
    pos: [f64; 4],
    relative: bool,
    relative_e: bool,
    feed: f64,
    tool: usize,
    fan: f64,
    temps: [f64; 16],
    accel_print: f64,
    accel_travel: f64,
    role: Option<u32>,
    width: Option<f64>,
    height: Option<f64>,
    seen_layer_change: bool,
    previous_z: f32,
    extruded: Vec<f64>,
    filament_area: f64,
}

impl State<'_> {
    fn flush(&mut self) -> io::Result<()> {
        if self.layer.segments.is_empty() {
            return Ok(());
        }
        let planned = attrs::plan(&self.layer.moves, &self.options.machine);
        let mut time = 0.;
        let attrs: Vec<Attr> = self
            .layer
            .segments
            .iter()
            .zip(&planned)
            .zip(self.layer.moves.iter().zip(&self.layer.temps))
            .map(|((s, &actual), (m, &temp))| {
                let length = glam::Vec3::from(s.a).distance(glam::Vec3::from(s.b)) as f64;
                if actual > 0. {
                    time += length / actual;
                }
                Attr::new(actual, attrs::volumetric(s), temp, m.accel)
            })
            .collect();
        let z = self.layer.z.unwrap_or(self.pos[2] as f32);
        self.builder.push_parsed(
            &self.layer.segments,
            &attrs,
            z,
            time as f32,
            !self.layer.written,
        )?;
        self.layer.segments.clear();
        self.layer.moves.clear();
        self.layer.temps.clear();
        self.layer.written = true;
        Ok(())
    }
    /// Ends the current layer (if it has records) and starts the next.
    fn next_layer(&mut self, z: Option<f32>) -> io::Result<()> {
        let had = self.layer.written || !self.layer.segments.is_empty();
        self.flush()?;
        if had {
            if let Some(z) = self.layer.z {
                self.previous_z = z;
            }
            self.layer = LayerBuf::default();
        }
        if z.is_some() {
            self.layer.z = z;
        }
        Ok(())
    }
    fn push(&mut self, segment: Segment, m: Move) -> io::Result<()> {
        self.layer.segments.push(segment);
        self.layer.moves.push(m);
        self.layer.temps.push(self.temps[self.tool.min(15)]);
        if self.layer.segments.len() >= LAYER_CHUNK {
            self.flush()?;
        }
        Ok(())
    }
    /// One straight move from the current position to `to` with `de` filament.
    fn line(&mut self, to: [f64; 3], de: f64) -> io::Result<()> {
        let a = [self.pos[0] as f32, self.pos[1] as f32, self.pos[2] as f32];
        let b = [to[0] as f32, to[1] as f32, to[2] as f32];
        let length = ((to[0] - self.pos[0]).powi(2)
            + (to[1] - self.pos[1]).powi(2)
            + (to[2] - self.pos[2]).powi(2))
        .sqrt();
        self.pos[0] = to[0];
        self.pos[1] = to[1];
        self.pos[2] = to[2];
        if length < 1e-5 {
            return Ok(());
        }
        let speed = self.feed.max(0.);
        if de > 1e-7 {
            // Layers without tags: a new one where extrusion changes height.
            if !self.options.layer_tags {
                match self.layer.z {
                    None => self.layer.z = Some(b[2]),
                    Some(z) if (b[2] - z).abs() > 0.01 && self.layer.extrusions > 0 => {
                        self.next_layer(Some(b[2]))?;
                    }
                    _ => {}
                }
            } else if self.layer.z.is_none() {
                self.layer.z = Some(b[2]);
            }
            let layer_z = self.layer.z.unwrap_or(b[2]);
            let height = self
                .height
                .filter(|h| *h > 0.)
                .unwrap_or_else(|| (layer_z - self.previous_z).max(0.) as f64);
            let height = if height > 0.005 { height } else { 0.2 };
            let width = self.width.filter(|w| *w > 0.).unwrap_or_else(|| {
                let area = de * self.filament_area / length;
                area / height + height * (1. - std::f64::consts::FRAC_PI_4)
            });
            let width = width.clamp(0.05, 5.);
            let role = self.role.unwrap_or(self.options.unknown.0);
            self.layer.extrusions += 1;
            let segment = Segment::new(a, b, [width, height], role, self.tool, speed, self.fan);
            let accel = self.accel_print;
            self.push(
                segment,
                Move {
                    a,
                    b,
                    feed: speed,
                    accel,
                    travel: false,
                },
            )
        } else {
            let segment = Segment::new(a, b, [0.08, 0.04], TRAVEL, self.tool, speed, 0.);
            let accel = self.accel_travel;
            self.push(
                segment,
                Move {
                    a,
                    b,
                    feed: speed,
                    accel,
                    travel: true,
                },
            )
        }
    }
}

/// Target of a move: absolute or relative coordinates, missing axes unchanged.
fn target(state: &State, l: &[u8]) -> ([f64; 3], f64) {
    let mut to = [state.pos[0], state.pos[1], state.pos[2]];
    for (i, axis) in b"XYZ".iter().copied().enumerate() {
        if let Some(v) = param(l, axis).filter(|v| v.is_finite()) {
            to[i] = if state.relative { to[i] + v } else { v };
        }
    }
    let de = match param(l, b'E').filter(|v| v.is_finite()) {
        Some(e) if state.relative || state.relative_e => e,
        Some(e) => e - state.pos[3],
        None => 0.,
    };
    (to, de)
}

/// The move pass: writes the preview records into `job`. `progress` gets bytes read.
pub fn parse(
    reader: impl BufRead,
    job: &Arc<TempJob>,
    options: &Options,
    file_time_s: Option<f64>,
    cancel: &AtomicBool,
    progress: impl FnMut(u64),
) -> Result<Parsed, Invalid> {
    let io_error = |e: io::Error| Invalid(format!("Mica could not write the preview: {e}"));
    let builder = Builder::new(job, &options.config, &[]).map_err(io_error)?;
    let mut s = State {
        builder,
        options,
        layer: LayerBuf::default(),
        pos: [0.; 4],
        relative: false,
        relative_e: false,
        feed: 25.,
        tool: 0,
        fan: 0.,
        temps: [0.; 16],
        accel_print: 0.,
        accel_travel: 0.,
        role: None,
        width: None,
        height: None,
        seen_layer_change: false,
        previous_z: 0.,
        extruded: vec![0.; 16],
        filament_area: std::f64::consts::PI * (options.filament_diameter / 2.).powi(2),
    };
    let mut io_failure: Option<io::Error> = None;
    let mut wipe = false;
    each_line(reader, cancel, progress, |raw| {
        let l = trim(raw);
        let Some(&first) = l.first() else {
            return Ok(());
        };
        if first == b';' {
            let c = trim(&l[1..]);
            let result = if c == b"LAYER_CHANGE" {
                if s.seen_layer_change {
                    s.next_layer(None)
                } else {
                    // The start G-code's moves (purge line) belong to the first layer.
                    s.seen_layer_change = true;
                    s.layer.z = None;
                    Ok(())
                }
            } else if let Some(v) = c.strip_prefix(b"Z:") {
                if s.layer.z.is_none() || s.layer.extrusions == 0 {
                    s.layer.z = std::str::from_utf8(v)
                        .ok()
                        .and_then(|v| v.trim().parse().ok());
                }
                Ok(())
            } else if let Some(v) = c.strip_prefix(b"TYPE:") {
                let name = String::from_utf8_lossy(v);
                s.role = role_of(&name);
                Ok(())
            } else if let Some(v) = c.strip_prefix(b"WIDTH:") {
                s.width = std::str::from_utf8(v)
                    .ok()
                    .and_then(|v| v.trim().parse().ok());
                Ok(())
            } else if let Some(v) = c.strip_prefix(b"HEIGHT:") {
                s.height = std::str::from_utf8(v)
                    .ok()
                    .and_then(|v| v.trim().parse().ok());
                Ok(())
            } else if c == b"WIPE_START" {
                wipe = true;
                Ok(())
            } else if c == b"WIPE_END" {
                wipe = false;
                Ok(())
            } else {
                Ok(())
            };
            if let Err(e) = result {
                io_failure = Some(e);
                return Err(Invalid(String::new()));
            }
            return Ok(());
        }
        let result: io::Result<()> = match word(l) {
            (b'G', 0 | 1) => {
                if let Some(f) = param(l, b'F').filter(|f| *f > 0. && f.is_finite()) {
                    s.feed = f / 60.;
                }
                let (to, de) = target(&s, l);
                if param(l, b'E').is_some() {
                    s.pos[3] += de;
                    if let Some(t) = s.extruded.get_mut(s.tool.min(15)) {
                        *t += de;
                    }
                }
                // Wipes move with the nozzle retracting: travel, not extrusion.
                let de = if wipe { de.min(0.) } else { de };
                s.line(to, de)
            }
            (b'G', n @ (2 | 3)) => {
                if let Some(f) = param(l, b'F').filter(|f| *f > 0. && f.is_finite()) {
                    s.feed = f / 60.;
                }
                let (to, de) = target(&s, l);
                if param(l, b'E').is_some() {
                    s.pos[3] += de;
                    if let Some(t) = s.extruded.get_mut(s.tool.min(15)) {
                        *t += de;
                    }
                }
                let de = if wipe { de.min(0.) } else { de };
                arc(&mut s, l, to, de, n == 2)
            }
            (b'G', 90) => {
                s.relative = false;
                Ok(())
            }
            (b'G', 91) => {
                s.relative = true;
                Ok(())
            }
            (b'G', 92) => {
                let mut any = false;
                for (i, axis) in b"XYZE".iter().copied().enumerate() {
                    if let Some(v) = param(l, axis).filter(|v| v.is_finite()) {
                        s.pos[i] = v;
                        any = true;
                    }
                }
                // A bare `G92` zeroes every axis.
                if !any {
                    s.pos = [0.; 4];
                }
                Ok(())
            }
            (b'M', 82) => {
                s.relative_e = false;
                Ok(())
            }
            (b'M', 83) => {
                s.relative_e = true;
                Ok(())
            }
            (b'M', 106) => {
                if matches!(param(l, b'P'), None | Some(0.)) {
                    s.fan = param(l, b'S').map_or(100., |v| (v / 255. * 100.).clamp(0., 100.));
                }
                Ok(())
            }
            (b'M', 107) => {
                if matches!(param(l, b'P'), None | Some(0.)) {
                    s.fan = 0.;
                }
                Ok(())
            }
            (b'M', 104 | 109) => {
                if let Some(t) = param(l, b'S').or_else(|| param(l, b'R')) {
                    let tool = param(l, b'T').map_or(s.tool, |t| t as usize).min(15);
                    s.temps[tool] = t;
                }
                Ok(())
            }
            (b'M', 204) => {
                if let Some(a) = param(l, b'S') {
                    s.accel_print = a;
                    s.accel_travel = a;
                }
                if let Some(a) = param(l, b'P') {
                    s.accel_print = a;
                }
                if let Some(a) = param(l, b'T') {
                    s.accel_travel = a;
                }
                Ok(())
            }
            (b'T', n) => {
                s.tool = (n as usize).min(15);
                Ok(())
            }
            _ => {
                if l.starts_with(b"SET_VELOCITY_LIMIT")
                    && let Some(a) = macro_param(l, "ACCEL")
                {
                    s.accel_print = a;
                    s.accel_travel = a;
                }
                Ok(())
            }
        };
        if let Err(e) = result {
            io_failure = Some(e);
            return Err(Invalid(String::new()));
        }
        Ok(())
    })
    .map_err(|e| match io_failure.take() {
        Some(io) => io_error(io),
        None => e,
    })?;
    s.flush().map_err(io_error)?;
    let State {
        builder, extruded, ..
    } = s;
    let mut preview = builder
        .finish_with(job.clone(), file_time_s)
        .map_err(io_error)?;
    if preview.count == 0 {
        return Err(Invalid(
            "This file has no toolpaths: there is nothing to preview".into(),
        ));
    }
    let (slot, label) = options.unknown;
    if preview.stats.roles[slot as usize].count > 0 {
        preview.relabel = Some((slot as usize, label));
    }
    Ok(Parsed {
        preview,
        extruded_mm: extruded,
    })
}

/// A `G2` / `G3` arc as Marlin cuts it: chords short enough for a 0.02 mm deviation and fifty
/// a second, 0.1–2 mm long (`process_G2_G3`). Arcs without `I`/`J` (or with `R`) are drawn as
/// a straight move.
fn arc(s: &mut State, l: &[u8], to: [f64; 3], de: f64, clockwise: bool) -> io::Result<()> {
    let (i, j) = (param(l, b'I'), param(l, b'J'));
    if i.is_none() && j.is_none() {
        return s.line(to, de);
    }
    let (i, j): (f64, f64) = (i.unwrap_or(0.), j.unwrap_or(0.));
    let start = [s.pos[0], s.pos[1], s.pos[2]];
    let center = [start[0] + i, start[1] + j];
    let rs = [start[0] - center[0], start[1] - center[1]];
    let re = [to[0] - center[0], to[1] - center[1]];
    let full = (to[0] - start[0]).abs() < 1e-6 && (to[1] - start[1]).abs() < 1e-6;
    let mut angle = if full {
        std::f64::consts::TAU
    } else {
        let a = (rs[0] * re[1] - rs[1] * re[0]).atan2(rs[0] * re[0] + rs[1] * re[1]);
        if a < 0. { a + std::f64::consts::TAU } else { a }
    };
    if clockwise {
        angle -= std::f64::consts::TAU;
    }
    let radius = (i * i + j * j).sqrt();
    if !radius.is_finite() || radius < 1e-6 {
        return s.line(to, de);
    }
    let segment = (8. * radius * 0.02)
        .sqrt()
        .min(s.feed.max(1.) / 50.)
        .clamp(0.1, 2.);
    let flat = radius * angle.abs();
    let segments = ((flat / segment + 0.8) as usize).clamp(1, 4096);
    let start_angle = rs[1].atan2(rs[0]);
    for k in 1..segments {
        let t = k as f64 / segments as f64;
        let a = start_angle + angle * t;
        let p = [
            center[0] + radius * a.cos(),
            center[1] + radius * a.sin(),
            start[2] + (to[2] - start[2]) * t,
        ];
        s.line(p, de / segments as f64)?;
    }
    s.line(to, de / segments as f64)
}
