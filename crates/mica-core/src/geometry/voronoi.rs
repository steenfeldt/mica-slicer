//! Voronoi diagram of line segments, with PrusaSlicer's detection and repair of degenerate diagrams.
//!
//! Boost's sweep line occasionally produces a broken diagram for nearly degenerate input (missing vertices,
//! edges crossing the input). PrusaSlicer detects the known failure modes and retries with the input rotated
//! by a few odd angles, mapping the vertices back afterwards; this module does the same.

use std::f64::consts::PI;

use boostvoronoi::prelude::{Builder, Line as BvLine, Point as BvPoint, SourceCategory};

use super::Point;

/// An input segment.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Line {
    pub a: Point,
    pub b: Point,
}

impl Line {
    pub fn new(a: Point, b: Point) -> Self {
        Self { a, b }
    }
}

/// What a Voronoi cell was generated by.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CellSource {
    /// The start point (`a`) of input segment `index`.
    SegmentStart,
    /// The end point (`b`) of input segment `index`.
    SegmentEnd,
    /// The segment itself.
    Segment,
}

#[derive(Clone, Copy, Debug)]
pub struct Cell {
    pub source_index: usize,
    pub source: CellSource,
    pub incident_edge: Option<usize>,
}

impl Cell {
    pub fn contains_point(&self) -> bool {
        self.source != CellSource::Segment
    }
    pub fn contains_segment(&self) -> bool {
        self.source == CellSource::Segment
    }
    pub fn is_degenerate(&self) -> bool {
        self.incident_edge.is_none()
    }
}

#[derive(Clone, Copy, Debug)]
pub struct Vertex {
    pub x: f64,
    pub y: f64,
    pub incident_edge: Option<usize>,
}

/// A half-edge. Twins are stored next to each other: the twin of `e` is `e ^ 1`.
#[derive(Clone, Copy, Debug)]
pub struct Edge {
    pub cell: usize,
    pub vertex0: Option<usize>,
    pub next: usize,
    pub prev: usize,
    pub linear: bool,
    pub primary: bool,
}

/// A Voronoi diagram in plain arrays, with Boost's half-edge conventions.
#[derive(Clone, Debug, Default)]
pub struct Diagram {
    pub cells: Vec<Cell>,
    pub vertices: Vec<Vertex>,
    pub edges: Vec<Edge>,
}

impl Diagram {
    pub fn twin(&self, e: usize) -> usize {
        e ^ 1
    }
    pub fn vertex1(&self, e: usize) -> Option<usize> {
        self.edges[e ^ 1].vertex0
    }
    pub fn is_finite(&self, e: usize) -> bool {
        self.edges[e].vertex0.is_some() && self.vertex1(e).is_some()
    }
    /// Next edge counter-clockwise around the start vertex of `e`.
    pub fn rot_next(&self, e: usize) -> usize {
        self.twin(self.edges[e].prev)
    }
    pub fn cell_of(&self, e: usize) -> &Cell {
        &self.cells[self.edges[e].cell]
    }
    pub fn vertex_point(&self, v: usize) -> (f64, f64) {
        (self.vertices[v].x, self.vertices[v].y)
    }
}

/// Why a diagram was judged broken (PrusaSlicer's `VoronoiDiagram::IssueType`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Issue {
    None,
    FiniteEdgeWithNonFiniteVertex,
    MissingVoronoiVertex,
    NonPlanarVoronoiDiagram,
    VoronoiEdgeIntersectingInputSegment,
    ParabolicVoronoiEdgeWithoutFocusPoint,
    /// The Voronoi builder rejected the input.
    BuildFailed,
}

/// Builds the diagram of `lines`, repairing it by rotation if a known issue shows up. Returns the
/// diagram and whether it is valid (no issue, or repaired). PrusaSlicer's `construct_voronoi` with
/// `try_to_repair_if_needed`.
pub fn construct(lines: &[Line]) -> (Diagram, bool) {
    super::voronoi_cache::get_or_build(lines, || construct_uncached(lines))
}

fn construct_uncached(lines: &[Line]) -> (Diagram, bool) {
    let Some(vd) = build(lines) else {
        return (Diagram::default(), false);
    };
    if detect_known_issues(&vd, lines) == Issue::None {
        return (vd, true);
    }
    let mut last = vd;
    for angle in [PI / 6.0, PI / 5.0, PI / 7.0, PI / 11.0] {
        match repair_by_rotation(lines, angle) {
            Some((vd, Issue::None)) => return (vd, true),
            Some((vd, _)) => last = vd,
            None => {}
        }
    }
    (last, false)
}

/// Runs the sweep line and copies the result (PrusaSlicer's `copy_to_local`).
fn build(lines: &[Line]) -> Option<Diagram> {
    let _timer = crate::timing::Span::new(crate::timing::Stage::VoronoiBuild);
    let fits = |v: i64| i32::try_from(v).is_ok();
    if !lines
        .iter()
        .all(|l| fits(l.a.x) && fits(l.a.y) && fits(l.b.x) && fits(l.b.y))
    {
        return None;
    }
    super::voronoi_probe::record(lines);
    let segs = lines.iter().map(|l| {
        BvLine::new(
            BvPoint {
                x: l.a.x as i32,
                y: l.a.y as i32,
            },
            BvPoint {
                x: l.b.x as i32,
                y: l.b.y as i32,
            },
        )
    });
    let sweep_timer = crate::timing::Span::new(crate::timing::Stage::VoronoiSweep);
    let out = Builder::<i32>::default()
        .with_segments(segs)
        .ok()?
        .build()
        .ok()?;
    drop(sweep_timer);
    let _copy_timer = crate::timing::Span::new(crate::timing::Stage::VoronoiCopy);
    let mut vd = Diagram {
        cells: Vec::with_capacity(out.cells().len()),
        vertices: Vec::with_capacity(out.vertices().len()),
        edges: Vec::with_capacity(out.edges().len()),
    };
    for c in out.cells() {
        vd.cells.push(Cell {
            source_index: c.source_index().usize(),
            source: match c.source_category() {
                SourceCategory::SegmentStart | SourceCategory::SinglePoint => {
                    CellSource::SegmentStart
                }
                SourceCategory::SegmentEnd => CellSource::SegmentEnd,
                SourceCategory::Segment => CellSource::Segment,
            },
            incident_edge: c.get_incident_edge().map(|e| e.usize()),
        });
    }
    for v in out.vertices() {
        vd.vertices.push(Vertex {
            x: v.x(),
            y: v.y(),
            incident_edge: v.get_incident_edge().ok().map(|e| e.usize()),
        });
    }
    for (i, e) in out.edges().iter().enumerate() {
        let twin = e.twin().ok()?.usize();
        if twin != (i ^ 1) {
            // The half-edge pairing every algorithm here relies on doesn't hold.
            return None;
        }
        vd.edges.push(Edge {
            cell: e.cell().ok()?.usize(),
            vertex0: e.vertex0().map(|v| v.usize()),
            next: e.next().map_or(i, |n| n.usize()),
            prev: e.prev().map_or(i, |p| p.usize()),
            linear: e.is_linear(),
            primary: e.is_primary(),
        });
    }
    Some(vd)
}

fn vertex_is_finite(v: &Vertex) -> bool {
    v.x.is_finite() && v.y.is_finite()
}

/// The input point a point cell was generated by.
pub fn source_point(cell: &Cell, lines: &[Line]) -> Point {
    let line = &lines[cell.source_index];
    if cell.source == CellSource::SegmentEnd {
        line.b
    } else {
        line.a
    }
}

fn detect_known_issues(vd: &Diagram, lines: &[Line]) -> Issue {
    let _timer = crate::timing::Span::new(crate::timing::Stage::VoronoiCheck);
    let edge_issue = detect_edge_issues(vd);
    if edge_issue != Issue::None {
        return edge_issue;
    }
    let cell_issue = detect_cell_issues(vd, lines);
    if cell_issue != Issue::None {
        return cell_issue;
    }
    if !is_planar_angle(vd, lines) {
        return Issue::NonPlanarVoronoiDiagram;
    }
    Issue::None
}

fn detect_edge_issues(vd: &Diagram) -> Issue {
    for e in 0..vd.edges.len() {
        if !vd.is_finite(e) {
            continue;
        }
        let (v0, v1) = (vd.edges[e].vertex0.unwrap(), vd.vertex1(e).unwrap());
        if !vertex_is_finite(&vd.vertices[v0]) || !vertex_is_finite(&vd.vertices[v1]) {
            return Issue::FiniteEdgeWithNonFiniteVertex;
        }
        if !vd.edges[e].linear
            && !vd.cell_of(e).contains_point()
            && !vd.cell_of(vd.twin(e)).contains_point()
        {
            return Issue::ParabolicVoronoiEdgeWithoutFocusPoint;
        }
    }
    Issue::None
}

/// Rounded vertex position (`VoronoiUtils::to_point`).
fn to_point(vd: &Diagram, v: usize) -> (i64, i64) {
    let p = &vd.vertices[v];
    (p.x.round() as i64, p.y.round() as i64)
}

/// The edges of a segment cell that run along its left side, from the segment's end back to its start
/// (`VoronoiUtils::compute_segment_cell_range`). `None` when a vertex at either endpoint is missing.
pub(crate) fn segment_cell_range(
    vd: &Diagram,
    cell: &Cell,
    lines: &[Line],
) -> Option<(usize, usize)> {
    let line = &lines[cell.source_index];
    let from = (line.a.x, line.a.y);
    let to = (line.b.x, line.b.y);
    let first = cell.incident_edge?;
    let (mut begin, mut end) = (None, None);
    let mut seen_possible_start = false;
    let mut after_start = false;
    let mut ending_edge_is_set_before_start = false;
    let mut e = first;
    let mut guard = 0;
    loop {
        if vd.is_finite(e) {
            let v0 = to_point(vd, vd.edges[e].vertex0.unwrap());
            let v1 = to_point(vd, vd.vertex1(e).unwrap());
            if v0 == to && !after_start {
                begin = Some(e);
                seen_possible_start = true;
            } else if seen_possible_start {
                after_start = true;
            }
            if v1 == from && (end.is_none() || ending_edge_is_set_before_start) {
                ending_edge_is_set_before_start = !after_start;
                end = Some(e);
            }
        }
        e = vd.edges[e].next;
        guard += 1;
        if e == first || guard > vd.edges.len() {
            break;
        }
    }
    Some((begin?, end?))
}

fn detect_cell_issues(vd: &Diagram, lines: &[Line]) -> Issue {
    for cell in &vd.cells {
        if cell.is_degenerate() || !cell.contains_segment() {
            continue;
        }
        let Some((begin, end)) = segment_cell_range(vd, cell, lines) else {
            return Issue::MissingVoronoiVertex;
        };
        let line = &lines[cell.source_index];
        let from = (line.a.x as f64, line.a.y as f64);
        let vec = ((line.b.x - line.a.x) as f64, (line.b.y - line.a.y) as f64);
        // All Voronoi vertices must lie left of the source segment.
        let mut e = begin;
        let mut guard = 0;
        while e != end {
            if !vd.is_finite(e) {
                return Issue::MissingVoronoiVertex;
            }
            let (x, y) = vd.vertex_point(vd.vertex1(e).unwrap());
            if vec.0 * (y - from.1) - vec.1 * (x - from.0) < 0.0 {
                return Issue::VoronoiEdgeIntersectingInputSegment;
            }
            e = vd.edges[e].next;
            guard += 1;
            if guard > vd.edges.len() {
                return Issue::MissingVoronoiVertex;
            }
        }
    }
    Issue::None
}

// --- Planarity check (VoronoiUtilsCgal::is_voronoi_diagram_planar_angle), in f64. ---

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Orientation {
    Left,
    Right,
    Collinear,
}

impl Orientation {
    fn of(v: f64) -> Self {
        if v > 0.0 {
            Orientation::Left
        } else if v < 0.0 {
            Orientation::Right
        } else {
            Orientation::Collinear
        }
    }
    fn opposite(self) -> Self {
        match self {
            Orientation::Left => Orientation::Right,
            Orientation::Right => Orientation::Left,
            Orientation::Collinear => Orientation::Collinear,
        }
    }
}

type V2 = (f64, f64);

fn orientation(p: V2, q: V2, r: V2) -> Orientation {
    Orientation::of((q.0 - p.0) * (r.1 - p.1) - (q.1 - p.1) * (r.0 - p.0))
}

fn pt(p: Point) -> V2 {
    (p.x as f64, p.y as f64)
}

struct Parabolic {
    focus: V2,
    directrix: (V2, V2),
    start: V2,
    focus_side: Orientation,
}

fn parabolic_segment(vd: &Diagram, e: usize, lines: &[Line]) -> Parabolic {
    let left = vd.cell_of(e);
    let right = vd.cell_of(vd.twin(e));
    let (point_cell, segment_cell) = if left.contains_point() {
        (left, right)
    } else {
        (right, left)
    };
    let focus = pt(source_point(point_cell, lines));
    let seg = &lines[segment_cell.source_index];
    let v0 = vd.vertex_point(vd.edges[e].vertex0.unwrap());
    let v1 = vd.vertex_point(vd.vertex1(e).unwrap());
    Parabolic {
        focus,
        directrix: (pt(seg.a), pt(seg.b)),
        start: v0,
        focus_side: orientation(v0, v1, focus).opposite(),
    }
}

/// Tangent of the parabola (focus `f`, directrix `u`–`v`) at `p`, oriented by `o`.
fn parabolic_tangent(p: V2, f: V2, u: V2, v: V2, o: Orientation) -> V2 {
    let d = (v.0 - u.0, v.1 - u.1);
    let dd = d.0 * d.0 + d.1 * d.1;
    let dp = d.0 * (p.0 - u.0) + d.1 * (p.1 - u.1);
    let fv = ((f.0 - u.0) * dd - d.0 * dp, (f.1 - u.1) * dd - d.1 * dp);
    // CGAL's Vector_2::perpendicular: counter-clockwise for a left turn.
    if o == Orientation::Left {
        (-fv.1, fv.0)
    } else {
        (fv.1, -fv.0)
    }
}

fn orientation_of_two_edges(vd: &Diagram, a: usize, b: usize, lines: &[Line]) -> Orientation {
    let (la, lb) = (vd.edges[a].linear, vd.edges[b].linear);
    if la && lb {
        let p = vd.vertex_point(vd.edges[a].vertex0.unwrap());
        let q = vd.vertex_point(vd.vertex1(a).unwrap());
        let r = vd.vertex_point(vd.vertex1(b).unwrap());
        orientation(p, q, r)
    } else if !la && !lb {
        let pa = parabolic_segment(vd, a, lines);
        let pb = parabolic_segment(vd, b, lines);
        let t0 = parabolic_tangent(
            pa.start,
            pa.focus,
            pa.directrix.0,
            pa.directrix.1,
            pa.focus_side,
        );
        let t1 = parabolic_tangent(
            pa.start,
            pb.focus,
            pb.directrix.0,
            pb.directrix.1,
            pb.focus_side,
        );
        Orientation::of(t0.0 * t1.1 - t0.1 * t1.0)
    } else {
        let (linear, parabolic) = if la { (a, b) } else { (b, a) };
        let par = parabolic_segment(vd, parabolic, lines);
        let q = vd.vertex_point(vd.vertex1(linear).unwrap());
        let t = parabolic_tangent(
            par.start,
            par.focus,
            par.directrix.0,
            par.directrix.1,
            par.focus_side,
        );
        let l = (q.0 - par.start.0, q.1 - par.start.1);
        let o = Orientation::of(t.0 * l.1 - t.1 * l.0);
        if !lb { o.opposite() } else { o }
    }
}

fn three_edges_are_ccw(
    vd: &Diagram,
    first: usize,
    second: usize,
    third: usize,
    lines: &[Line],
) -> bool {
    match orientation_of_two_edges(vd, first, second, lines) {
        Orientation::Collinear => {
            orientation_of_two_edges(vd, first, third, lines) == Orientation::Right
        }
        Orientation::Left => {
            let o1 = orientation_of_two_edges(vd, first, third, lines);
            let o2 = orientation_of_two_edges(vd, second, third, lines);
            o1 != Orientation::Left || o2 != Orientation::Right
        }
        Orientation::Right => {
            let o1 = orientation_of_two_edges(vd, first, third, lines);
            let o2 = orientation_of_two_edges(vd, second, third, lines);
            o1 == Orientation::Right || o2 == Orientation::Left
        }
    }
}

fn is_planar_angle(vd: &Diagram, lines: &[Line]) -> bool {
    for vertex in &vd.vertices {
        let Some(start) = vertex.incident_edge else {
            continue;
        };
        let mut edges = Vec::new();
        let mut e = start;
        let mut guard = 0;
        loop {
            if vd.is_finite(e)
                && vertex_is_finite(&vd.vertices[vd.edges[e].vertex0.unwrap()])
                && vertex_is_finite(&vd.vertices[vd.vertex1(e).unwrap()])
            {
                edges.push(e);
            }
            e = vd.rot_next(e);
            guard += 1;
            if e == start || guard > vd.edges.len() {
                break;
            }
        }
        if edges.len() > 2 {
            let n = edges.len();
            for i in 0..n {
                let prev = edges[(i + n - 1) % n];
                let next = edges[(i + 1) % n];
                if !three_edges_are_ccw(vd, prev, edges[i], next, lines) {
                    return false;
                }
            }
        }
    }
    true
}

// --- Repair by rotation. ---

fn rotate_point(p: Point, angle: f64) -> Point {
    let (s, c) = angle.sin_cos();
    let (x, y) = (p.x as f64, p.y as f64);
    Point::new(
        (c * x - s * y).round() as i64,
        (c * y + s * x).round() as i64,
    )
}

/// Rebuilds the diagram from the input rotated by `angle` and rotates the vertices back; vertices that
/// sit on input segment endpoints are snapped to the exact original endpoints.
fn repair_by_rotation(lines: &[Line], angle: f64) -> Option<(Diagram, Issue)> {
    let rotated: Vec<Line> = lines
        .iter()
        .map(|l| Line::new(rotate_point(l.a, angle), rotate_point(l.b, angle)))
        .collect();
    let mut vd = build(&rotated)?;
    let issue = detect_known_issues(&vd, &rotated);

    // Colour: 0 = rotate back, otherwise (segment index + 1) << 1 | (1 for the end point `b`).
    let mut color = vec![0usize; vd.vertices.len()];
    for cell in &vd.cells {
        if cell.is_degenerate() || !cell.contains_segment() {
            continue;
        }
        if let Some((begin, end)) = segment_cell_range(&vd, cell, &rotated) {
            let start_vertex = vd.vertex1(end).unwrap();
            if color[start_vertex] == 0 {
                color[start_vertex] = (cell.source_index + 1) << 1;
            }
            let end_vertex = vd.edges[begin].vertex0.unwrap();
            if color[end_vertex] == 0 {
                color[end_vertex] = ((cell.source_index + 1) << 1) | 1;
            }
        }
    }
    let (s, c) = (-angle).sin_cos();
    for (v, &col) in vd.vertices.iter_mut().zip(&color) {
        if col == 0 {
            let (x, y) = (v.x, v.y);
            v.x = c * x - s * y;
            v.y = c * y + s * x;
        } else {
            let line = &lines[(col >> 1) - 1];
            let p = if col & 1 == 1 { line.b } else { line.a };
            v.x = p.x as f64;
            v.y = p.y as f64;
        }
    }
    Some((vd, issue))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn square_lines(size: i64) -> Vec<Line> {
        let p = [
            Point::new(0, 0),
            Point::new(size, 0),
            Point::new(size, size),
            Point::new(0, size),
        ];
        (0..4).map(|i| Line::new(p[i], p[(i + 1) % 4])).collect()
    }

    #[test]
    fn square_diagram_is_valid_and_paired() {
        let lines = square_lines(1_000_000);
        let (vd, valid) = construct(&lines);
        assert!(valid);
        assert!(!vd.edges.is_empty());
        // Each segment has a cell, and so does each endpoint.
        assert!(vd.cells.iter().filter(|c| c.contains_segment()).count() == 4);
        for e in 0..vd.edges.len() {
            assert_eq!(vd.twin(vd.twin(e)), e);
        }
        // The centre of the square is a Voronoi vertex.
        assert!(
            vd.vertices
                .iter()
                .any(|v| (v.x - 500_000.0).abs() < 1.0 && (v.y - 500_000.0).abs() < 1.0)
        );
    }

    #[test]
    fn rotation_repair_maps_vertices_back() {
        let lines = square_lines(1_000_000);
        let (vd, issue) = repair_by_rotation(&lines, PI / 6.0).unwrap();
        assert_eq!(issue, Issue::None);
        // Corners snap back to the exact input points, the centre rotates back to the centre.
        assert!(vd.vertices.iter().any(|v| v.x == 1_000_000.0 && v.y == 0.0));
        assert!(
            vd.vertices
                .iter()
                .any(|v| (v.x - 500_000.0).abs() < 2.0 && (v.y - 500_000.0).abs() < 2.0)
        );
    }
}
